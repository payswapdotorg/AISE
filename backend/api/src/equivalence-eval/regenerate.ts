/**
 * HFX-301 — the equivalence benchmark's REGENERATION CLI (the
 * committed-golden writer — the PROD-027 reality-eval `regenerate.ts` /
 * HFX-204 building-benchmark pattern).
 *
 * Regenerates the committed benchmark artifacts DETERMINISTICALLY
 * (canonical JSON: recursively sorted keys, 2-space indent, trailing
 * newline):
 *
 *   tools/equivalence-eval/scenario.json
 *       the committed corpus (the version-pinned manifest header + the
 *       scene + the 33 pairs)
 *   tools/equivalence-eval/fixtures/expected-outcomes.json
 *       the committed golden run (the per-pair outcome views + the suite
 *       summary with the aggregate digests)
 *
 * Run from the repo root (or the backend/api workspace):
 *
 *   bun backend/api/src/equivalence-eval/regenerate.ts
 *
 * The committed files regenerate BYTE-IDENTICALLY (no clock, no
 * randomness, no network). The golden tests (the backend golden.test.ts
 * + the tools check runner) recompute and byte-compare — a harness/corpus
 * change without a re-run fails `bun run verify`.
 */

import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { goldenExpectedOutcomesJson, goldenScenarioSuiteJson } from "./testkit";
import { EQUIVALENCE_EVAL_SUITE_ID } from "./registry";
import { EQUIVALENCE_CORPUS } from "./corpus";

const REPO_ROOT = resolve(import.meta.dir, "..", "..", "..", "..");
const SCENARIO_FILE = resolve(REPO_ROOT, "tools", "equivalence-eval", "scenario.json");
const OUTCOMES_FILE = resolve(
  REPO_ROOT,
  "tools",
  "equivalence-eval",
  "fixtures",
  "expected-outcomes.json",
);

// CLI output seam (the lint gate's no-console rule: a CLI's stdout IS its
// output contract — deterministic transcript lines, never console.*).
function out(line: string): void {
  process.stdout.write(`${line}\n`);
}

const scenarioJson = goldenScenarioSuiteJson();
writeFileSync(SCENARIO_FILE, scenarioJson, "utf8");
out(`equivalence-eval scenario suite written: tools/equivalence-eval/scenario.json`);
out(
  `  suite ${EQUIVALENCE_EVAL_SUITE_ID} — ${EQUIVALENCE_CORPUS.length} committed pairs ` +
    `(${scenarioJson.length} bytes)`,
);

const outcomesJson = await goldenExpectedOutcomesJson();
writeFileSync(OUTCOMES_FILE, outcomesJson, "utf8");
out(`equivalence-eval expected outcomes written: tools/equivalence-eval/fixtures/expected-outcomes.json`);
out(`  ${outcomesJson.length} bytes (canonical JSON — regenerated byte-identically)`);
