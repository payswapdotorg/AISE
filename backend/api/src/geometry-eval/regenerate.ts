/**
 * HFX-302 — the geometry substitution benchmark's REGENERATION CLI (the
 * committed-golden writer — the HFX-301 equivalence-eval `regenerate.ts`
 * pattern).
 *
 * Regenerates the committed benchmark artifacts DETERMINISTICALLY
 * (canonical JSON: recursively sorted keys, 2-space indent, trailing
 * newline):
 *
 *   tools/geometry-eval/scenario.json
 *       the committed corpus (the version-pinned manifest header + the
 *       scene + the 30 sequences)
 *   tools/geometry-eval/fixtures/expected-outcomes.json
 *       the committed golden run (the per-sequence outcome views + the
 *       suite summary with the aggregate digests)
 *
 * Run from the repo root (or the backend/api workspace):
 *
 *   bun backend/api/src/geometry-eval/regenerate.ts
 *
 * The committed files regenerate BYTE-IDENTICALLY (no clock, no
 * randomness, no network). The golden tests (the backend golden.test.ts +
 * the tools check runner) recompute and byte-compare — a harness/corpus
 * change without a re-run fails `bun run verify`.
 */

import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { goldenCorpusSuiteJson, goldenOutcomesJson } from "./testkit";
import { GEOMETRY_EVAL_SUITE_ID } from "./registry";
import { GEOMETRY_CORPUS } from "./corpus";

const REPO_ROOT = resolve(import.meta.dir, "..", "..", "..", "..");
const SCENARIO_FILE = resolve(REPO_ROOT, "tools", "geometry-eval", "scenario.json");
const OUTCOMES_FILE = resolve(
  REPO_ROOT,
  "tools",
  "geometry-eval",
  "fixtures",
  "expected-outcomes.json",
);

// CLI output seam (the lint gate's no-console rule: a CLI's stdout IS its
// output contract — deterministic transcript lines, never console.*).
function out(line: string): void {
  process.stdout.write(`${line}\n`);
}

const scenarioJson = goldenCorpusSuiteJson();
writeFileSync(SCENARIO_FILE, scenarioJson, "utf8");
out(`geometry-eval scenario suite written: tools/geometry-eval/scenario.json`);
out(
  `  suite ${GEOMETRY_EVAL_SUITE_ID} — ${GEOMETRY_CORPUS.length} committed sequences ` +
    `(${scenarioJson.length} bytes)`,
);

const outcomesJson = goldenOutcomesJson();
writeFileSync(OUTCOMES_FILE, outcomesJson, "utf8");
out(
  `geometry-eval expected outcomes written: tools/geometry-eval/fixtures/expected-outcomes.json`,
);
out(`  ${outcomesJson.length} bytes (canonical JSON — regenerated byte-identically)`);
