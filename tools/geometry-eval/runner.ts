interface Json {
  readonly [key: string]: unknown;
}

function asRecord(value: unknown, label: string): Json {
  if (typeof value !== "object" || value === null || Array.isArray(value)) {
    throw new Error(`${label}: expected a JSON object`);
  }
  return value as Json;
}

export interface PointView {
  readonly pointKind: string;
  readonly subjectId: string;
  readonly equal: boolean;
  readonly divergenceKind?: string;
  readonly detail: string;
  readonly dimension?: string;
  readonly unit?: string;
  readonly referenceValue?: number;
  readonly candidateValue?: number;
  readonly declaredTolerance?: { readonly absolute: number; readonly relative: number };
  readonly absoluteDelta?: number;
  readonly relativeDelta?: number;
  readonly allowedAbsolute?: number;
  readonly allowedBy?: string;
  readonly referenceResult?: string;
  readonly candidateResult?: string;
}

export interface OutcomeView {
  readonly sequenceId: string;
  readonly substituteProfileId: string;
  readonly expectation: string;
  readonly observed: string;
  readonly expectationMet: boolean;
  readonly referenceLane: {
    readonly providerId: string;
    readonly technologyVersion: string;
    readonly executed: boolean;
    readonly benchmarkRecordId: string;
    readonly provenanceManifestId: string;
  };
  readonly substituteLane: {
    readonly providerId: string;
    readonly technologyVersion: string;
    readonly executed: boolean;
    readonly unsupportedFamily?: string;
    readonly benchmarkRecordId: string;
    readonly provenanceManifestId: string;
  };
  readonly comparison: {
    readonly verdict: string;
    readonly totalPoints: number;
    readonly equalPoints: number;
    readonly divergentPoints: readonly string[];
    readonly failureKind?: string;
    readonly failureKinds: readonly string[];
    readonly points: readonly PointView[];
  } | null;
  readonly referenceProjectionDigest: string;
}

export interface SequenceView {
  readonly sequenceId: string;
  readonly expectation: string;
  readonly substituteProfileId: string;
  readonly declaredDifferenceKind?: string;
  readonly operations: readonly {
    readonly operationType: string;
  }[];
  readonly notes?: string;
}

export interface GeometryArtifacts {
  readonly scenarioSuite: Json;
  readonly sequences: readonly SequenceView[];
  readonly outcomesSuite: Json;
  readonly outcomes: readonly OutcomeView[];
}

/** Loads the committed artifacts (throws on structural mismatch). */
export function loadGeometryArtifacts(): GeometryArtifacts {
  const scenarioSuite = asRecord(readJson(SCENARIO_PATH), "scenario.json");
  const outcomesSuite = asRecord(readJson(OUTCOMES_PATH), "expected-outcomes.json");
  const sequences = (scenarioSuite["sequences"] as unknown[]).map((entry, index) =>
    asRecord(entry, `scenario.json sequences[${index}]`),
  ) as unknown as readonly SequenceView[];
  const outcomes = (outcomesSuite["outcomes"] as unknown[]).map((entry, index) =>
    asRecord(entry, `expected-outcomes.json outcomes[${index}]`),
  ) as unknown as readonly OutcomeView[];
  return { scenarioSuite, sequences, outcomesSuite, outcomes };
}

