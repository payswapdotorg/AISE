/**
 * Verifies the committed HFX-302 artifacts (pure; every check is named,
 * deterministic and listed in the module header).
 */
export function verifyGeometryArtifacts(): GeometryArtifactReport {
  const { scenarioSuite, sequences, outcomesSuite, outcomes } = loadGeometryArtifacts();
  const checks: GeometryArtifactCheck[] = [];
  const check = (id: string, passed: boolean, detail: string): void => {
    checks.push({ id, passed, detail });
  };
  const sequenceOf = (sequenceId: string): SequenceView => {
    const found = sequences.find((entry) => entry.sequenceId === sequenceId);
    if (found === undefined) {
      throw new Error(`runner: no committed sequence for '${sequenceId}'`);
    }
    return found;
  };
  const outcomeOf = (sequenceId: string): OutcomeView => {
    const found = outcomes.find((entry) => entry.sequenceId === sequenceId);
    if (found === undefined) {
      throw new Error(`runner: no committed outcome for '${sequenceId}'`);
    }
    return found;
  };

  /* 1. Coherence ---------------------------------------------------- */

  const suiteId = String(scenarioSuite["suiteId"] ?? "");
  const scenarioPins = asRecord(scenarioSuite["pins"], "scenario.pins");
  const outcomesPins = asRecord(outcomesSuite["pins"], "outcomes.pins");
  check(
    "coherence-suite-identity",
    suiteId === "geometry-eval-suite/1" &&
      String(outcomesSuite["suiteId"] ?? "") === suiteId &&
      String(scenarioSuite["benchmarkId"] ?? "") === "geometry-eval-suite/1" &&
      String(outcomesSuite["benchmarkId"] ?? "") === "geometry-eval-suite/1" &&
      String(scenarioSuite["version"] ?? "") === "1.0.0" &&
      String(scenarioSuite["codeVersion"] ?? "") === "hfx-302/geometry-eval/1" &&
      String(outcomesSuite["codeVersion"] ?? "") === "hfx-302/geometry-eval/1",
    `both artifacts pin suiteId '${suiteId}', benchmarkId 'geometry-eval-suite/1', version '1.0.0', codeVersion 'hfx-302/geometry-eval/1'`,
  );
  const sequenceIds = sequences.map((entry) => entry.sequenceId);
  check(
    "coherence-sequence-identity",
    new Set(sequenceIds).size === sequenceIds.length && sequenceIds.length === SEQUENCE_COUNT,
    `${sequenceIds.length} sequences with unique ids (22 compatible + 5 declared-incompatible + 4 unsupported)`,
  );
  const outcomeIds = outcomes.map((outcome) => outcome.sequenceId);
  check(
    "coherence-outcome-alignment",
    outcomeIds.length === sequenceIds.length &&
      sequenceIds.every((id) => outcomeIds.includes(id)) &&
      outcomeIds.every((id) => sequenceIds.includes(id)) &&
      Number(outcomesSuite["sequenceCount"] ?? -1) === outcomes.length,
    "the outcome ids align 1:1 with the sequence ids",
  );
  check(
    "coherence-canonical-form",
    canonicalJson(readJson(SCENARIO_PATH)) === readFileSync(SCENARIO_PATH, "utf8") &&
      canonicalJson(readJson(OUTCOMES_PATH)) === readFileSync(OUTCOMES_PATH, "utf8"),
    "both committed artifacts are canonical JSON (sorted keys, 2-space, trailing newline)",
  );
  const pinsEqual =
    scenarioPins["engineKind"] === outcomesPins["engineKind"] &&
    scenarioPins["engineCodeVersion"] === outcomesPins["engineCodeVersion"] &&
    scenarioPins["substituteImplementationVersion"] ===
      outcomesPins["substituteImplementationVersion"] &&
    scenarioPins["toleranceModelVersion"] === outcomesPins["toleranceModelVersion"] &&
    scenarioPins["corpusDigest"] === outcomesPins["corpusDigest"];
  const digestShape = /^[0-9a-f]{64}$/;
  check(
    "coherence-version-pins",
    pinsEqual &&
      String(scenarioPins["engineKind"] ?? "") === "aise-solution-engine" &&
      String(scenarioPins["engineCodeVersion"] ?? "") === "1.0.0" &&
      String(scenarioPins["substituteImplementationVersion"] ?? "") ===
        "geometry-substitute/discretized-accumulation/1" &&
      String(scenarioPins["toleranceModelVersion"] ?? "") === "hfx-302/quantity-tolerance/1" &&
      digestShape.test(String(scenarioPins["corpusDigest"] ?? "")),
    "the version-pinned manifest header (engine kind+version, substitute implementation, tolerance model, corpus digest) rides both artifacts identically",
  );

  /* 2. The three-cell behavior matrix ------------------------------- */

  const byExpectation: Record<string, number> = {};
  for (const entry of sequences) {
    byExpectation[entry.expectation] = (byExpectation[entry.expectation] ?? 0) + 1;
  }
  const missingCells = SUBSTITUTION_CELLS.filter((cell) => (byExpectation[cell] ?? 0) === 0);
  check(
    "matrix-three-cells-present",
    missingCells.length === 0,
    missingCells.length === 0
      ? "all three behavior-matrix cells carry committed sequences (22/5/4)"
      : `missing cells: ${missingCells.join(", ")}`,
  );
  check(
    "matrix-cell-counts",
    Object.entries(CELL_COUNTS).every(([cell, count]) => (byExpectation[cell] ?? -1) === count),
    "the committed matrix is exactly 22 compatible + 5 declared-incompatible + 4 unsupported-by-substitute",
  );
  const expectationMismatches = outcomes.filter((outcome) => !outcome.expectationMet);
  check(
    "matrix-expectation-gate",
    expectationMismatches.length === 0,
    expectationMismatches.length === 0
      ? "every committed outcome's observed cell (and declared kind) satisfies its sequence's expectation"
      : `mismatches: ${expectationMismatches.map((outcome) => outcome.sequenceId).join(", ")}`,
  );
  const declaredWithoutKind = outcomes.filter(
    (outcome) => outcome.expectation === "declared-incompatible" && outcome.comparison?.failureKind === undefined,
  );
  check(
    "matrix-declared-kind-required",
    declaredWithoutKind.length === 0,
    "every declared-incompatible outcome records its difference kind (declared, never discovered)",
  );

  /* 3. The substitution proof ---------------------------------------- */

  const compatible = outcomes.filter((outcome) => outcome.observed === "compatible");
  const notCleanCompatible = compatible.filter(
    (outcome) =>
      outcome.comparison === null ||
      outcome.comparison.verdict !== "compatible" ||
      outcome.comparison.equalPoints !== outcome.comparison.totalPoints ||
      (outcome.comparison.divergentPoints?.length ?? 0) !== 0 ||
      !outcome.comparison.points.every((point) => point.equal),
  );
  check(
    "substitution-canonical-compatibility",
    notCleanCompatible.length === 0,
    notCleanCompatible.length === 0
      ? `all ${compatible.length} compatible outcomes carry ZERO divergent points over the five canonical comparison kinds (quantities, per-check validation, verdict, topology, BOQ lines)`
      : `unclean compatibles: ${notCleanCompatible.map((outcome) => outcome.sequenceId).join(", ")}`,
  );
  const offVocabularyPoints = outcomes.flatMap((outcome) =>
    (outcome.comparison?.points ?? [])
      .filter((point) => !COMPARISON_POINT_KINDS.includes(point.pointKind))
      .map((point) => `${outcome.sequenceId}:${point.pointKind}`),
  );
  check(
    "substitution-point-vocabulary",
    offVocabularyPoints.length === 0,
    offVocabularyPoints.length === 0
      ? "every committed comparison point rides the five canonical kinds (quantity-value, validation-check, validation-verdict, topology-constraint, boq-line) — no invented point kind"
      : `off-vocabulary points: ${offVocabularyPoints.join(", ")}`,
  );
  const lanesNotExecuted = compatible.filter(
    (outcome) => !outcome.referenceLane.executed || !outcome.substituteLane.executed,
  );
  check(
    "substitution-both-lanes-executed",
    lanesNotExecuted.length === 0,
    "every compatible outcome executed BOTH lanes through the same adapter call",
  );
  const compatibleFamilies = new Set<string>();
  for (const outcome of compatible) {
    for (const operation of sequenceOf(outcome.sequenceId).operations) {
      compatibleFamilies.add(operation.operationType);
    }
  }
  const familyGaps = OPERATION_FAMILIES.filter((family) => !compatibleFamilies.has(family));
  check(
    "substitution-ten-family-coverage",
    familyGaps.length === 0,
    familyGaps.length === 0
      ? "ALL TEN documented v1 operation families are covered by the compatible cells"
      : `family gaps: ${familyGaps.join(", ")}`,
  );

  /* 4. The honest differences ---------------------------------------- */

  const declaredIncompatible = outcomes.filter(
    (outcome) => outcome.observed === "declared-incompatible",
  );
  const dishonestDifferences = declaredIncompatible.filter((outcome) =>
    outcome.comparison === null ||
    (outcome.comparison.divergentPoints?.length ?? 0) === 0 ||
    outcome.comparison.failureKind === undefined ||
    !CLOSED_FAILURE_KINDS.includes(outcome.comparison.failureKind ?? "") ||
    !(outcome.comparison.failureKinds ?? []).every((kind) => CLOSED_FAILURE_KINDS.includes(kind)) ||
    outcome.comparison.failureKind !== sequenceOf(outcome.sequenceId).declaredDifferenceKind,
  );
  check(
    "differences-honest-and-declared",
    declaredIncompatible.length === 5 && dishonestDifferences.length === 0,
    declaredIncompatible.length === 5 && dishonestDifferences.length === 0
      ? "all 5 declared-incompatible outcomes carry ≥ 1 divergent point, record the closed-vocabulary kind their corpus entry declared up front, and agree with the corpus declaration — never hidden"
      : `dishonest differences: ${dishonestDifferences.map((outcome) => outcome.sequenceId).join(", ")}`,
  );
  const unbreachedDivergences = declaredIncompatible.flatMap((outcome) =>
    (outcome.comparison?.points ?? [])
      .filter(
        (point) =>
          !point.equal &&
          (point.pointKind === "quantity-value" || point.pointKind === "boq-line") &&
          (point.absoluteDelta ?? 0) <= (point.allowedAbsolute ?? 0),
      )
      .map((point) => `${outcome.sequenceId}:${point.subjectId}`),
  );
  check(
    "differences-tolerance-breaches-itemized",
    unbreachedDivergences.length === 0 &&
      declaredIncompatible.every((outcome) =>
        (outcome.comparison?.points ?? []).some(
          (point) =>
            !point.equal &&
            (point.pointKind === "quantity-value" || point.pointKind === "boq-line") &&
            (point.absoluteDelta ?? 0) > (point.allowedAbsolute ?? 0),
        ),
      ),
    "every declared-incompatible outcome's divergent tolerance legs genuinely BREACH the declared allowance (absoluteDelta > allowedAbsolute), each carrying the declared tolerance and the observed delta — itemized, never rounded away",
  );
  const kindMismatches = declaredIncompatible.filter((outcome) => {
    const entry = sequenceOf(outcome.sequenceId);
    return entry.expectation !== "declared-incompatible";
  });
  check(
    "differences-match-corpus-declaration",
    kindMismatches.length === 0,
    "every declared-incompatible outcome's sequence declares the same cell in the committed corpus",
  );

  /* 5. The designed unsupported outcomes ----------------------------- */

  const unsupported = outcomes.filter(
    (outcome) => outcome.observed === "unsupported-by-substitute",
  );
  const unsupportedShapeViolations = unsupported.filter(
    (outcome) =>
      outcome.substituteLane.executed ||
      outcome.substituteLane.unsupportedFamily === undefined ||
      !RESTRICTED_OMITTED_FAMILIES.includes(outcome.substituteLane.unsupportedFamily ?? "") ||
      !outcome.referenceLane.executed ||
      outcome.comparison !== null,
  );
  check(
    "designed-unsupported-recorded",
    unsupported.length === 4 && unsupportedShapeViolations.length === 0,
    unsupported.length === 4 && unsupportedShapeViolations.length === 0
      ? "all 4 unsupported outcomes record the undeclared family (typed, never computed), leave the comparison null, and the reference lane still executed — the engine governs both lanes equally"
      : `shape violations: ${unsupportedShapeViolations.map((outcome) => outcome.sequenceId).join(", ")}`,
  );
  const namedFamilies = [...new Set(unsupported.map((o) => o.substituteLane.unsupportedFamily ?? ""))];
  check(
    "designed-unsupported-family-set",
    namedFamilies.sort().join(",") === [...RESTRICTED_OMITTED_FAMILIES].sort().join(","),
    `the named families are exactly the restricted profile's committed omissions [${RESTRICTED_OMITTED_FAMILIES.join(", ")}]`,
  );

  /* 6. The tolerance discipline -------------------------------------- */

  const toleranceLegs = outcomes.flatMap((outcome) =>
    (outcome.comparison?.points ?? []).filter(
      (point) => point.pointKind === "quantity-value" || point.pointKind === "boq-line",
    ),
  );
  const toleranceFieldGaps = toleranceLegs.filter(
    (point) =>
      point.declaredTolerance === undefined ||
      point.absoluteDelta === undefined ||
      point.allowedAbsolute === undefined ||
      point.referenceValue === undefined ||
      point.candidateValue === undefined,
  );
  check(
    "tolerance-declared-on-every-leg",
    toleranceLegs.length > 0 && toleranceFieldGaps.length === 0,
    `every one of the ${toleranceLegs.length} quantity/BOQ comparison legs carries its declared per-dimension tolerance and the observed deltas — never implicit`,
  );
  const toleranceTableMismatches = toleranceLegs.filter((point) => {
    const declared = DECLARED_TOLERANCES[point.dimension ?? ""];
    return (
      declared === undefined ||
      point.declaredTolerance?.absolute !== declared.absolute ||
      point.declaredTolerance?.relative !== declared.relative
    );
  });
  check(
    "tolerance-table-matches-declaration",
    toleranceTableMismatches.length === 0,
    "every leg's declared tolerance equals the committed per-dimension table (length/area/volume: abs 0.05 ⊕ rel 1 %; count: EXACT)",
  );
  const withinLogicViolations = toleranceLegs.filter((point) => {
    const allowed =
      Math.max(
        point.declaredTolerance?.absolute ?? 0,
        (point.declaredTolerance?.relative ?? 0) * Math.abs(point.referenceValue ?? 0),
      ) || 0;
    return (
      Math.abs((allowed ?? 0) - (point.allowedAbsolute ?? 0)) > 1e-12 ||
      point.equal !== ((point.absoluteDelta ?? 0) <= (point.allowedAbsolute ?? 0))
    );
  });
  check(
    "tolerance-predicate-recomputes",
    withinLogicViolations.length === 0,
    "every leg's within/outside verdict re-derives from the declared terms (allowed = max(absolute, relative × |reference|); within ⟺ absoluteDelta ≤ allowed) — the comparison logic itself is re-verified",
  );
  const countSlack = toleranceLegs.filter(
    (point) => point.dimension === "count" && (point.declaredTolerance?.absolute ?? 0) !== 0,
  );
  check(
    "tolerance-count-exact",
    countSlack.length === 0,
    "integer count quantities carry ZERO tolerance (a count mismatch is a semantic divergence, never noise)",
  );

  /* 7. The control-plane emission ----------------------------------- */

  const malformedArtifacts = outcomes.filter(
    (outcome) =>
      !digestShape.test(outcome.referenceLane.benchmarkRecordId) ||
      !digestShape.test(outcome.referenceLane.provenanceManifestId) ||
      !digestShape.test(outcome.substituteLane.benchmarkRecordId) ||
      !digestShape.test(outcome.substituteLane.provenanceManifestId) ||
      !digestShape.test(outcome.referenceProjectionDigest),
  );
  check(
    "emission-content-addressed",
    malformedArtifacts.length === 0,
    "every outcome carries 64-hex content-addressed record + manifest ids for BOTH lanes plus the reference projection digest",
  );
  const committedSummary = asRecord(outcomesSuite["summary"], "summary");
  check(
    "emission-aggregate-digests",
    digestShape.test(String(committedSummary["provenanceManifestDigest"] ?? "")) &&
      digestShape.test(String(committedSummary["benchmarkRecordDigest"] ?? "")),
    "the aggregate digests are 64-hex",
  );

  /* 8. Summary recomputation (independent arithmetic) ---------------- */

  const byObserved: Record<string, number> = {};
  let expectationMatches = 0;
  for (const outcome of outcomes) {
    byObserved[outcome.observed] = (byObserved[outcome.observed] ?? 0) + 1;
    if (outcome.expectationMet) {
      expectationMatches += 1;
    }
  }
  const recomputedManifestDigest = sha256Hex(
    canonicalJson(
      outcomes.flatMap((outcome) => [
        outcome.referenceLane.provenanceManifestId,
        outcome.substituteLane.provenanceManifestId,
      ]),
    ),
  );
  const recomputedRecordDigest = sha256Hex(
    canonicalJson(
      outcomes.flatMap((outcome) => [
        outcome.referenceLane.benchmarkRecordId,
        outcome.substituteLane.benchmarkRecordId,
      ]),
    ),
  );
  const committedByExpectation = committedSummary["byExpectation"] as Record<string, number>;
  const committedByObserved = committedSummary["byObserved"] as Record<string, number>;
  const summaryEqual =
    String(committedSummary["total"] ?? "") === String(outcomes.length) &&
    Object.entries(CELL_COUNTS).every(
      ([cell, count]) => (committedByExpectation?.[cell] ?? -1) === count,
    ) &&
    Object.entries(CELL_COUNTS).every(
      ([cell, count]) => (committedByObserved?.[cell] ?? -1) === count,
    ) &&
    Number(committedSummary["expectationMatches"] ?? -1) === expectationMatches &&
    String(committedSummary["provenanceManifestDigest"] ?? "") === recomputedManifestDigest &&
    String(committedSummary["benchmarkRecordDigest"] ?? "") === recomputedRecordDigest;
  check(
    "summary-recomputes",
    summaryEqual,
    "the committed suite summary re-derives from the outcome rows alone (independent arithmetic incl. the ordered-manifest-id digest over both lanes)",
  );

  /* 9. The corpus declaration consistency --------------------------- */

  const corpusMismatches = sequences.filter((entry) => {
    const outcome = outcomeOf(entry.sequenceId);
    return outcome.expectation !== entry.expectation;
  });
  check(
    "corpus-declaration-consistency",
    corpusMismatches.length === 0,
    "every committed sequence's declared expectation matches its outcome's expectation",
  );

  /* The per-dimension observed delta extremes (the tolerance report's data). */
  const extremes: Record<string, { maxAbsoluteDelta: number; maxRelativeDelta: number; breaches: number }> = {};
  for (const point of toleranceLegs) {
    const dimension = point.dimension ?? "";
    const entry =
      extremes[dimension] ?? { maxAbsoluteDelta: 0, maxRelativeDelta: 0, breaches: 0 };
    entry.maxAbsoluteDelta = Math.max(entry.maxAbsoluteDelta, point.absoluteDelta ?? 0);
    entry.maxRelativeDelta = Math.max(entry.maxRelativeDelta, point.relativeDelta ?? 0);
    if (!point.equal) {
      entry.breaches += 1;
    }
    extremes[dimension] = entry;
  }

  const ok = checks.every((entry) => entry.passed);
  return {
    ok,
    checks,
    summary: {
      total: outcomes.length,
      byExpectation: Object.fromEntries(
        Object.entries(byExpectation).sort(([a], [b]) => a.localeCompare(b)),
      ),
      byObserved: Object.fromEntries(
        Object.entries(byObserved).sort(([a], [b]) => a.localeCompare(b)),
      ),
      expectationMatches,
      compatibleFamilyCoverage: (committedSummary["compatibleFamilyCoverage"] as string[]) ?? [],
      unsupportedFamilyCoverage: (committedSummary["unsupportedFamilyCoverage"] as string[]) ?? [],
      provenanceManifestDigest: String(committedSummary["provenanceManifestDigest"] ?? ""),
      benchmarkRecordDigest: String(committedSummary["benchmarkRecordDigest"] ?? ""),
      toleranceExtremes: Object.fromEntries(
        Object.entries(extremes).sort(([a], [b]) => a.localeCompare(b)),
      ),
    },
  };
}

