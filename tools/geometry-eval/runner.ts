const isDirectRun =
  typeof process !== "undefined" &&
  typeof process.argv !== "undefined" &&
  process.argv[1] !== undefined &&
  resolve(process.argv[1]) === resolve(import.meta.path);

if (isDirectRun) {
  // The regeneration delegation: the boundary matrix forbids importing
  // the backend module from tools/, so --update-goldens SPAWNS the
  // backend-zone regeneration CLI (a pure subprocess boundary — the
  // committed artifacts are then rewritten deterministically).
  if (process.argv.includes("--update-goldens")) {
    const { spawnSync } = await import("node:child_process");
    const repoRoot = resolve(import.meta.dir, "..", "..");
    const result = spawnSync(
      process.execPath,
      ["backend/api/src/geometry-eval/regenerate.ts"],
      { cwd: repoRoot, stdio: "inherit" },
    );
    if (result.status !== 0) {
      process.stdout.write("goldens update FAILED\n");
      process.exit(1);
    }
  }

  const report = verifyGeometryArtifacts();
  process.stdout.write(
    "HFX-302 geometry-eval — geometry/validation technology substitution committed corpus check runner\n",
  );
  const { scenarioSuite } = loadGeometryArtifacts();
  const pins = asRecord(scenarioSuite["pins"], "pins");
  process.stdout.write(
    `  suite: ${String(scenarioSuite["suiteId"])} v${String(scenarioSuite["version"])} (code ${String(scenarioSuite["codeVersion"])})\n`,
  );
  process.stdout.write(
    `  pins: engine ${String(pins["engineKind"])}/${String(pins["engineCodeVersion"])} · substitute ${String(pins["substituteImplementationVersion"])} · tolerance-model ${String(pins["toleranceModelVersion"])}\n`,
  );
  process.stdout.write(`  corpus digest: ${String(pins["corpusDigest"])}\n`);
  for (const [cell, count] of Object.entries(report.summary.byExpectation)) {
    process.stdout.write(`  ${cell}: ${count} sequences\n`);
  }
  for (const outcome of loadGeometryArtifacts().outcomes) {
    const verdict =
      outcome.observed === "compatible"
        ? `compatible (${outcome.comparison?.equalPoints ?? 0}/${outcome.comparison?.totalPoints ?? 0} points equal)`
        : outcome.observed === "declared-incompatible"
          ? `declared-incompatible [${outcome.comparison?.failureKinds?.join(", ")}] on [${outcome.comparison?.divergentPoints?.join(", ")}]`
          : `unsupported-by-substitute (family: ${outcome.substituteLane.unsupportedFamily ?? "?"})`;
    process.stdout.write(
      `  [${outcome.expectationMet ? "met" : "MISMATCH"}] ${outcome.sequenceId}: ${verdict}\n`,
    );
  }
  for (const [dimension, extremes] of Object.entries(report.summary.toleranceExtremes)) {
    process.stdout.write(
      `  tolerance ${dimension}: max |Δ| ${extremes.maxAbsoluteDelta} · max rel Δ ${(extremes.maxRelativeDelta * 100).toFixed(2)}% · breaches ${extremes.breaches} (declared abs ${DECLARED_TOLERANCES[dimension]?.absolute} ⊕ rel ${(DECLARED_TOLERANCES[dimension]?.relative ?? 0) * 100}%)\n`,
    );
  }
  process.stdout.write(`  provenance-manifest digest: ${report.summary.provenanceManifestDigest}\n`);
  process.stdout.write(`  benchmark-record digest: ${report.summary.benchmarkRecordDigest}\n`);
  process.stdout.write(
    `  ten-family compatible coverage: ${report.summary.compatibleFamilyCoverage.length}/10 families\n`,
  );
  for (const entry of report.checks) {
    process.stdout.write(`  [${entry.passed ? "pass" : "FAIL"}] ${entry.id}: ${entry.detail}\n`);
  }
  process.stdout.write(report.ok ? "RUNNER: PASS\n" : "RUNNER: FAIL\n");
  process.exit(report.ok ? 0 : 1);
}
