/**
 * HFX-302 — the geometry/validation technology substitution benchmark
 * CHECK RUNNER (the tools/ pickup — the equivalence-eval convention,
 * mirroring tools/equivalence-eval/runner.ts).
 *
 * Wired into the root `bun run verify` (this directory's
 * benchmark.test.ts is a tools/ test, picked up by the root `bun test`).
 *
 * The boundary matrix forbids tools → packages/backend imports, so this
 * runner consumes the COMMITTED ARTIFACTS AS DATA — exactly the
 * equivalence-eval/solution-eval discipline: the committed corpus
 * descriptor (`tools/geometry-eval/scenario.json`) and the committed
 * golden run (`fixtures/expected-outcomes.json`, regenerated by the
 * backend-side testkit where the harness, the engine, the substitute and
 * the BOQ derivation CAN be imported — run `bun
 * tools/geometry-eval/runner.ts --update-goldens`). The LIVE
 * byte-for-byte regeneration check lives in the backend-side golden test
 * for the same boundary reason.
 *
 * What this runner proves over the committed data:
 *
 *  1. COHERENCE — both artifacts parse, their suite/benchmark identities
 *     agree and are pinned, the sequence ids are unique and align 1:1
 *     with the outcome ids, both files are canonical JSON, and the
 *     version-pinned manifest header (engine kind+codeVersion, substitute
 *     implementation version, tolerance-model version, corpus digest)
 *     rides BOTH headers identically;
 *  2. THE THREE-CELL BEHAVIOR MATRIX — every expectation class is present
 *     (compatible / declared-incompatible / unsupported-by-substitute)
 *     and every outcome's observed cell satisfies its sequence's declared
 *     expectation (the benchmark's own gate);
 *  3. THE SUBSTITUTION PROOF — every compatible outcome carries ZERO
 *     divergent points over the five canonical comparison kinds
 *     (quantity-value, validation-check, validation-verdict,
 *     topology-constraint, boq-line) with BOTH lanes executed, ALL TEN
 *     operation families covered;
 *  4. THE HONEST DIFFERENCES — every declared-incompatible outcome
 *     carries ≥ 1 divergent point, records the closed-vocabulary kind it
 *     declared up front, and every divergent tolerance leg BREACHES the
 *     declared tolerance (absolute delta > the declared allowance) —
 *     never a divergence below tolerance, never a hidden breach;
 *  5. THE DESIGNED UNSUPPORTED OUTCOMES — every unsupported outcome names
 *     the undeclared family, the reference lane still executed, and the
 *     named families are exactly the restricted profile's committed
 *     omissions;
 *  6. THE TOLERANCE DISCIPLINE — every quantity/BOQ comparison point
 *     carries its declared per-dimension tolerance (abs + rel) and the
 *     observed deltas; within-tolerance points have absoluteDelta ≤
 *     allowedAbsolute, breached points exceed it; count quantities are
 *     exact (zero tolerance, zero delta on equal points);
 *  7. THE CONTROL-PLANE EMISSION — every outcome carries 64-hex
 *     content-addressed record + manifest ids for BOTH lanes, and the
 *     aggregate digests are 64-hex;
 *  8. THE INDEPENDENT SUMMARY RECOMPUTATION — the committed suite summary
 *     re-derives from the outcome rows alone (independent arithmetic),
 *     including the ordered-manifest-id digest (sha-256 over the
 *     canonical JSON of the ordered manifest ids, both lanes interleaved
 *     per sequence);
 *  9. THE CORPUS DECLARATION CONSISTENCY — every committed sequence's
 *     declared expectation matches its outcome's expectation.
 *
 * Determinism: pure reads of committed files + pure arithmetic; no clock,
 * no randomness, no network, no package imports.
 *
 * Exit code 0 = every check passed; 1 = a check failed (the gate).
 */

