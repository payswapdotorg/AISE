/** The full verification report (the benchmark.test.ts + CLI consumption). */
export interface MapAnythingRunnerReport {
  readonly ok: boolean;
  readonly checks: readonly CheckResult[];
  readonly summary: {
    readonly total: number;
    readonly byCell: Readonly<Record<string, number>>;
    readonly byVariant: Readonly<Record<string, number>>;
    readonly byFailureKind: Readonly<Record<string, number>>;
    readonly expectedMatches: number;
  };
  readonly providers: readonly Json[];
  readonly variants: readonly Json[];
  readonly comparisons: readonly Json[];
}

/** Verifies the committed artifacts and aggregates the report. */
export function verifyMapAnythingEvalArtifacts(): MapAnythingRunnerReport {
  const checks = runAllChecks();
  const { runOutcomes, variants, comparisons } = loadExpectedOutcomes();
  const byCell: Record<string, number> = {};
  const byVariant: Record<string, number> = {};
  const byFailureKind: Record<string, number> = {};
  let expectedMatches = 0;
  for (const outcome of runOutcomes) {
    const cell = String(outcome["matrixCell"]);
    byCell[cell] = (byCell[cell] ?? 0) + 1;
    const variant = String(outcome["variant"]);
    byVariant[variant] = (byVariant[variant] ?? 0) + 1;
    if (outcome["expectedMatch"] === true) {
      expectedMatches += 1;
    }
    for (const kind of asArray(outcome["failureObservationKinds"], "kinds")) {
      const entry = String(kind);
      byFailureKind[entry] = (byFailureKind[entry] ?? 0) + 1;
    }
  }
  const sortCounts = (counts: Record<string, number>): Readonly<Record<string, number>> =>
    Object.fromEntries(Object.entries(counts).sort(([a], [b]) => a.localeCompare(b)));
  return {
    ok: checks.every((entry) => entry.ok),
    checks,
    summary: {
      total: runOutcomes.length,
      byCell: sortCounts(byCell),
      byVariant: sortCounts(byVariant),
      byFailureKind: sortCounts(byFailureKind),
      expectedMatches,
    },
    providers: loadScenarioSuite().providers,
    variants,
    comparisons,
  };
}

