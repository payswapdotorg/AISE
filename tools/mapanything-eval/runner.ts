/** 1a. The suite identity is pinned (suite/benchmark/code version/execution mode/license). */
export function checkSuiteIdentity(): CheckResult {
  const { suite } = loadScenarioSuite();
  const { outcomes } = loadExpectedOutcomes();
  const expectations: readonly [string, unknown, unknown][] = [
    ["suiteId", suite["suiteId"], "mapanything-recon-benchmark/1"],
    ["version", suite["version"], "1.0.0"],
    ["codeVersion", suite["codeVersion"], "hfx-101/mapanything-eval/1"],
    ["executionMode", suite["executionMode"], "deterministic-in-repo-doubles"],
    ["licenseStatus", suite["licenseStatus"], "evaluation-only"],
    ["providerFamily", suite["providerFamily"], "mapanything"],
    ["taskCount", suite["taskCount"], 8],
    ["runCount", suite["runCount"], 12],
    ["outcomes.suiteId", outcomes["suiteId"], "mapanything-recon-benchmark/1"],
    ["outcomes.runCount", outcomes["runCount"], 12],
    ["outcomes.executionMode", outcomes["executionMode"], "deterministic-in-repo-doubles"],
  ];
  for (const [key, actual, expected] of expectations) {
    if (actual !== expected) {
      return check("suite-identity", false, `${key}: expected '${String(expected)}', got '${String(actual)}'`);
    }
  }
  return check(
    "suite-identity",
    true,
    "suite mapanything-recon-benchmark/1 (1.0.0), code hfx-101/mapanything-eval/1, deterministic in-repo doubles, evaluation-only",
  );
}

/** 1b. The registered candidate + the reference-path provider blocks. */
export function checkProviders(): CheckResult {
  const { providers } = loadScenarioSuite();
  if (providers.length !== 3) {
    return check("providers-registered", false, `expected 3 provider blocks, got ${providers.length}`);
  }
  const candidate = providers.find((provider) => provider["variant"] === "mapanything");
  if (candidate === undefined) {
    return check("providers-registered", false, "the registered MapAnything candidate block is missing");
  }
  if (candidate["providerId"] !== "mapanything" || candidate["technologyVersion"] !== "eval-doubles-1") {
    return check("providers-registered", false, "the candidate's identity is wrong");
  }
  if (candidate["licenseStatus"] !== "evaluation-only") {
    return check("providers-registered", false, "the candidate must be evaluation-only");
  }
  if (typeof candidate["profileDigest"] !== "string" || !/^[0-9a-f]{64}$/.test(candidate["profileDigest"])) {
    return check("providers-registered", false, "the candidate's profile digest is not 64-hex");
  }
  const capabilities = asArray(candidate["capabilities"], "capabilities").map(String);
  for (const capability of ["reconstruction", "depth", "multi-image-reconstruction", "metric-depth", "registration"]) {
    if (!capabilities.includes(capability)) {
      return check("providers-registered", false, `the candidate must declare capability '${capability}'`);
    }
  }
  const referenceIds = providers
    .filter((provider) => provider["variant"] !== "mapanything")
    .map((provider) => String(provider["providerId"]));
  if (
    referenceIds.sort().join(",") !==
    ["fixture-reconstruction-provider", "fixture-reality-depth-provider"].sort().join(",")
  ) {
    return check("providers-registered", false, `wrong reference-path providers: [${referenceIds.join(", ")}]`);
  }
  for (const provider of providers) {
    if (typeof provider["profileDigest"] !== "string" || !/^[0-9a-f]{64}$/.test(provider["profileDigest"])) {
      return check("providers-registered", false, `provider '${String(provider["providerId"])}' digest is not 64-hex`);
    }
  }
  return check(
    "providers-registered",
    true,
    "the registered MapAnything candidate (evaluation-only) + the two existing reference-path providers, all with 64-hex profile digests",
  );
}

/** 1c. The corpus covers the mandated cells, task kinds, revisions + uncertainty. */
export function checkCorpusCoverage(): CheckResult {
  const { tasks } = loadScenarioSuite();
  if (tasks.length !== 8) {
    return check("corpus-coverage", false, `expected 8 tasks, got ${tasks.length}`);
  }
  const cells = new Map<string, number>();
  const kinds = new Set<string>();
  for (const task of tasks) {
    const cell = String(task["matrixCell"]);
    cells.set(cell, (cells.get(cell) ?? 0) + 1);
    kinds.add(String(task["taskKind"]));
    const revisions = asArray(task["evidenceRevisions"], "evidenceRevisions");
    if (revisions.length === 0) {
      return check("corpus-coverage", false, `task '${String(task["taskId"])}' declares no evidence revisions`);
    }
    const uncertainty = task["uncertainty"];
    const cellKinds: readonly string[] = ["grounded-pass", "degraded-evidence"];
    if (cellKinds.includes(cell) && (uncertainty === null || uncertainty === undefined)) {
      return check("corpus-coverage", false, `task '${String(task["taskId"])}' (cell ${cell}) must declare its uncertainty`);
    }
  }
  for (const cell of BEHAVIOR_MATRIX_CELLS) {
    if ((cells.get(cell) ?? 0) === 0) {
      return check("corpus-coverage", false, `behavior-matrix cell '${cell}' has no fixture`);
    }
  }
  for (const kind of DECLARED_TASKS) {
    if (!kinds.has(kind)) {
      return check("corpus-coverage", false, `task kind '${kind}' is not exercised`);
    }
  }
  if (!kinds.has("novel-view-synthesis")) {
    return check("corpus-coverage", false, "the unsupported-task fixture is missing");
  }
  return check(
    "corpus-coverage",
    true,
    `8 tasks: all four matrix cells covered (${[...cells.entries()].map(([cell, count]) => `${cell}×${count}`).join(", ")}); multi-image, metric-depth and registration task kinds all exercised`,
  );
}

/** 1d. The twelve runs are coherent (unique ids, reality-eval seals, pinned benchmark ids, per-task pairing). */
export function checkRunsCoherent(): CheckResult {
  const { runs, tasks } = loadScenarioSuite();
  if (runs.length !== 12) {
    return check("runs-coherent", false, `expected 12 runs, got ${runs.length}`);
  }
  const ids = new Set<string>();
  for (const run of runs) {
    const runId = String(run["runId"]);
    if (ids.has(runId)) {
      return check("runs-coherent", false, `duplicate run id '${runId}'`);
    }
    ids.add(runId);
    const scenario = asRecord(run["scenario"], "scenario");
    if (scenario["kind"] !== "reality-eval-scenario" || scenario["schemaVersion"] !== "reality-eval-scenario/1") {
      return check("runs-coherent", false, `run '${runId}': the scenario descriptor carries the wrong seal`);
    }
    const capability = String(scenario["capability"]);
    const expectedBenchmark = LANE_BENCHMARK_IDS[capability];
    if (expectedBenchmark === undefined || scenario["benchmarkId"] !== expectedBenchmark) {
      return check("runs-coherent", false, `run '${runId}': benchmarkId is not the pinned '${String(expectedBenchmark)}'`);
    }
    const input = asRecord(scenario["input"], "input");
    if (input["kind"] !== "provider-input" || input["capability"] !== capability) {
      return check("runs-coherent", false, `run '${runId}': the input fixture's capability is incoherent`);
    }
    const taskOfRun = tasks.find((task) => String(task["taskId"]) === String(run["taskId"]));
    if (taskOfRun === undefined) {
      return check("runs-coherent", false, `run '${runId}' references no committed task`);
    }
  }
  // every task has its MapAnything run; the four grounded tasks additionally have a reference run:
  for (const task of tasks) {
    const taskId = String(task["taskId"]);
    const hasMapAnything = runs.some((run) => run["variant"] === "mapanything" && run["taskId"] === taskId);
    if (!hasMapAnything) {
      return check("runs-coherent", false, `task '${taskId}' has no MapAnything run`);
    }
    const referenceVariant =
      String(task["capability"]) === "depth" ? "reference-depth" : "reference-reconstruction";
    const hasReference = runs.some((run) => run["variant"] === referenceVariant && run["taskId"] === taskId);
    if (task["matrixCell"] === "grounded-pass" && !hasReference) {
      return check("runs-coherent", false, `grounded task '${taskId}' has no reference-path run (the same evidence must be evaluated through BOTH)`);
    }
    if (task["matrixCell"] !== "grounded-pass" && hasReference) {
      return check("runs-coherent", false, `non-grounded task '${taskId}' must not carry a reference run`);
    }
  }
  return check(
    "runs-coherent",
    true,
    "12 runs (8 MapAnything + 4 reference-path): reality-eval seals, pinned benchmark ids, per-task pairing over the same evidence",
  );
}

/** 2. The outcomes align 1:1 with the runs and every expectation matched. */
export function checkOutcomesCoherent(): CheckResult {
  const { runs } = loadScenarioSuite();
  const { runOutcomes } = loadExpectedOutcomes();
  if (runOutcomes.length !== 12) {
    return check("outcomes-coherent", false, `expected 12 run outcomes, got ${runOutcomes.length}`);
  }
  const runIds = new Set(runs.map((run) => String(run["runId"])));
  for (const outcome of runOutcomes) {
    const runId = String(outcome["runId"]);
    if (!runIds.has(runId)) {
      return check("outcomes-coherent", false, `outcome '${runId}' references no committed run`);
    }
    if (outcome["expectedMatch"] !== true) {
      return check("outcomes-coherent", false, `outcome '${runId}': the expectation did not match`);
    }
    if (outcome["verdictMatch"] !== true || outcome["failureKindMatch"] !== true) {
      return check("outcomes-coherent", false, `outcome '${runId}': the verdict/failure-kind did not match`);
    }
    if (typeof outcome["derivedVersionId"] !== "string" || !/^drv-[0-9a-f]{24}$/.test(outcome["derivedVersionId"])) {
      return check("outcomes-coherent", false, `outcome '${runId}': no derived reconstruction version addressed`);
    }
  }
  const versionIds = runOutcomes.map((outcome) => String(outcome["derivedVersionId"]));
  if (new Set(versionIds).size !== versionIds.length) {
    return check("outcomes-coherent", false, "derived reconstruction version ids are not unique");
  }
  return check(
    "outcomes-coherent",
    true,
    "12 outcomes aligned 1:1 with the runs; every expectation matched; unique derived versions",
  );
}

/** 3. THE BEHAVIOR MATRIX (the mandated cells — these checks FAIL if the behavior regresses). */
export function checkBehaviorMatrix(): CheckResult {
  const { runOutcomes } = loadExpectedOutcomes();
  const byCell = new Map<string, Json[]>();
  for (const outcome of runOutcomes) {
    const cell = String(outcome["matrixCell"]);
    const bucket = byCell.get(cell) ?? [];
    bucket.push(outcome);
    byCell.set(cell, bucket);
  }
  for (const cell of BEHAVIOR_MATRIX_CELLS) {
    if ((byCell.get(cell) ?? []).length === 0) {
      return check("behavior-matrix", false, `cell '${cell}' has no run outcome`);
    }
  }
  // grounded-pass: content answers, pass, zero observations; the candidate declares the per-answer
  // sigma (the reference path honestly declares NO per-answer uncertainty — its calibration is
  // none-declared; recorded, never fabricated):
  for (const outcome of byCell.get("grounded-pass") ?? []) {
    if (outcome["verdict"] !== "pass" || outcome["normalizedStatus"] !== "ok") {
      return check("behavior-matrix", false, `grounded-pass run '${String(outcome["runId"])}' must answer content and pass`);
    }
    if (asArray(outcome["failureObservationKinds"], "kinds").length !== 0) {
      return check("behavior-matrix", false, `grounded-pass run '${String(outcome["runId"])}' must carry zero failure observations`);
    }
    const uncertainty = asRecord(outcome["uncertainty"], "uncertainty");
    if (uncertainty["surfaced"] !== true) {
      return check("behavior-matrix", false, `grounded-pass run '${String(outcome["runId"])}': the uncertainty characteristic was not surfaced`);
    }
    const isCandidate = outcome["variant"] === "mapanything";
    const declared = uncertainty["declaredSigmaM"];
    if (isCandidate) {
      if (declared === null || declared !== uncertainty["expectedSigmaM"]) {
        return check("behavior-matrix", false, `grounded-pass run '${String(outcome["runId"])}' must declare the corpus-expected per-answer sigma`);
      }
    } else if (declared !== null) {
      return check("behavior-matrix", false, `reference run '${String(outcome["runId"])}' must not fabricate a per-answer uncertainty`);
    }
  }
  // degraded-evidence: the capture requirement + the bounded uncertainty, NEVER downgraded geometry:
  for (const outcome of byCell.get("degraded-evidence") ?? []) {
    if (outcome["normalizedStatus"] !== "failed") {
      return check("behavior-matrix", false, `degraded-evidence run '${String(outcome["runId"])}' must answer an explicit refusal (never downgraded geometry)`);
    }
    const failure = asRecord(outcome["normalizedFailure"], "normalizedFailure");
    if (failure["kind"] !== "unsupported-data") {
      return check("behavior-matrix", false, `degraded-evidence run '${String(outcome["runId"])}': the refusal kind must be unsupported-data`);
    }
    const detail = String(failure["detail"]);
    if (!detail.includes("capture requirement") || !detail.includes("bounded uncertainty: sigma >= 0.05")) {
      return check("behavior-matrix", false, `degraded-evidence run '${String(outcome["runId"])}': the capture requirement + the bounded uncertainty must be surfaced`);
    }
    const uncertainty = asRecord(outcome["uncertainty"], "uncertainty");
    if (uncertainty["refusalBoundSigmaM"] !== 0.05) {
      return check("behavior-matrix", false, `degraded-evidence run '${String(outcome["runId"])}': the refusal-bound sigma was not surfaced`);
    }
  }
  // failed-invocation: the typed failure + the explicit non-ready/fallback state, NO outputs:
  for (const outcome of byCell.get("failed-invocation") ?? []) {
    if (outcome["normalizedStatus"] !== "failed") {
      return check("behavior-matrix", false, `failed-invocation run '${String(outcome["runId"])}' must answer the typed failure (no fabricated geometry)`);
    }
    const failure = asRecord(outcome["normalizedFailure"], "normalizedFailure");
    if (failure["kind"] !== "resource-exhaustion") {
      return check("behavior-matrix", false, `failed-invocation run '${String(outcome["runId"])}': the failure kind must be resource-exhaustion`);
    }
    const detail = String(failure["detail"]);
    if (!detail.includes("non-ready") || !detail.includes(DECLARED_FALLBACK)) {
      return check("behavior-matrix", false, `failed-invocation run '${String(outcome["runId"])}'): the non-ready state + the declared fallback must be surfaced`);
    }
    const fallback = asRecord(outcome["fallbackState"], "fallbackState");
    if (fallback["nonReady"] !== true || fallback["surfaced"] !== true) {
      return check("behavior-matrix", false, `failed-invocation run '${String(outcome["runId"])}': the fallback state was not surfaced`);
    }
  }
  // unsupported-task-combination: the explicit unsupported refusal for an out-of-set task:
  for (const outcome of byCell.get("unsupported-task-combination") ?? []) {
    if (outcome["normalizedStatus"] !== "failed") {
      return check("behavior-matrix", false, `unsupported-task run '${String(outcome["runId"])}' must refuse (never a guess)`);
    }
    const failure = asRecord(outcome["normalizedFailure"], "normalizedFailure");
    if (failure["kind"] !== "unsupported-data") {
      return check("behavior-matrix", false, `unsupported-task run '${String(outcome["runId"])}': the refusal kind must be unsupported-data`);
    }
    if (!String(failure["detail"]).includes("outside the declared capability set")) {
      return check("behavior-matrix", false, `unsupported-task run '${String(outcome["runId"])}': the refusal must name the out-of-set task`);
    }
  }
  const counts = [...byCell.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([cell, bucket]) => `${cell}×${bucket.length}`)
    .join(", ");
  return check("behavior-matrix", true, `all four mandated cells exhibited and correct (${counts})`);
}

/** 4a. Content addressing: every record's recordId re-derives from its own content. */
export function checkRecordContentAddressing(): CheckResult {
  const { runOutcomes, variants } = loadExpectedOutcomes();
  const records = [
    ...runOutcomes.map((outcome) => asRecord(outcome["record"], "record")),
    ...variants.flatMap((variant) =>
      asArray(variant["lanes"], "lanes").map((lane) =>
        asRecord(asRecord(lane, "lane")["consolidatedRecord"], "consolidatedRecord"),
      ),
    ),
  ];
  for (const record of records) {
    const { recordId, ...rest } = record;
    const identityInput = {
      kind: "provider-benchmark-record",
      providerId: rest["providerId"],
      technologyVersion: rest["technologyVersion"],
      benchmarkId: rest["benchmarkId"],
      capability: rest["capability"],
      metrics: rest["metrics"],
      failureObservations: rest["failureObservations"],
      resourceObservations: rest["resourceObservations"],
      reproduction: rest["reproduction"],
    };
    const derived = digestOf(identityInput);
    if (recordId !== derived) {
      return check("record-content-addressing", false, `recordId ${String(recordId)} != derived ${derived}`);
    }
  }
  return check(
    "record-content-addressing",
    true,
    `${records.length} records (12 per-run + 4 consolidated) re-derive their content addresses`,
  );
}

/** 4b. Every manifest's manifestId re-derives + chains its record 1:1. */
export function checkManifestContentAddressing(): CheckResult {
  const { runOutcomes, variants } = loadExpectedOutcomes();
  const pairs = [
    ...runOutcomes.map((outcome) => ({
      manifest: asRecord(outcome["manifest"], "manifest"),
      record: asRecord(outcome["record"], "record"),
    })),
    ...variants.flatMap((variant) =>
      asArray(variant["lanes"], "lanes").map((lane) => {
        const laneRecord = asRecord(lane, "lane");
        return {
          manifest: asRecord(laneRecord["consolidatedManifest"], "consolidatedManifest"),
          record: asRecord(laneRecord["consolidatedRecord"], "consolidatedRecord"),
        };
      }),
    ),
  ];
  for (const { manifest, record } of pairs) {
    const { manifestId, ...rest } = manifest;
    const derived = digestOf(rest);
    if (manifestId !== derived) {
      return check("manifest-content-addressing", false, `manifestId ${String(manifestId)} != derived ${derived}`);
    }
    const references = asArray(manifest["benchmarkRecordReferences"], "references");
    const digests = asArray(manifest["benchmarkRecordDigests"], "digests");
    if (references.length !== 1 || digests.length !== 1) {
      return check("manifest-content-addressing", false, "a manifest must chain exactly one record");
    }
    if (references[0] !== record["recordId"]) {
      return check("manifest-content-addressing", false, "the manifest's record reference does not match its record");
    }
    if (digests[0] !== digestOf(record)) {
      return check("manifest-content-addressing", false, "the manifest's record digest does not re-derive from the record");
    }
  }
  return check(
    "manifest-content-addressing",
    true,
    `${pairs.length} manifests re-derive and chain their records 1:1`,
  );
}

/** 4c. Every input digest re-derives from the run's own input fixture (the capture-set evidence included). */
export function checkInputDigests(): CheckResult {
  const { runs } = loadScenarioSuite();
  const { runOutcomes } = loadExpectedOutcomes();
  const digestByRunId = new Map(
    runs.map((run) => {
      const input = asRecord(asRecord(run["scenario"], "scenario")["input"], "input");
      return [
        String(run["runId"]),
        digestOf({ kind: "provider-input", capability: input["capability"], payload: input["payload"] }),
      ];
    }),
  );
  for (const outcome of runOutcomes) {
    const runId = String(outcome["runId"]);
    const record = asRecord(outcome["record"], "record");
    const reproduction = asRecord(record["reproduction"], "reproduction");
    const expected = digestByRunId.get(runId);
    if (expected === undefined) {
      return check("input-digests", false, `no committed run '${runId}'`);
    }
    if (reproduction["inputsDigest"] !== expected) {
      return check("input-digests", false, `outcome '${runId}': the inputsDigest does not re-derive from the run's input fixture`);
    }
    if (outcome["inputDigest"] !== expected) {
      return check("input-digests", false, `outcome '${runId}': the projected input digest disagrees`);
    }
  }
  return check("input-digests", true, "12 input digests re-derive from the scenario inputs (capture sets included)");
}

/** 5. The closed failure vocabulary (no invented failure kinds). */
export function checkClosedVocabulary(): CheckResult {
  const vocabulary = new Set<string>(CLOSED_FAILURE_KINDS);
  const { runOutcomes, variants, comparisons } = loadExpectedOutcomes();
  let observationCount = 0;
  for (const outcome of runOutcomes) {
    const record = asRecord(outcome["record"], "record");
    for (const observation of asArray(record["failureObservations"], "failureObservations")) {
      observationCount += 1;
      if (!vocabulary.has(String(asRecord(observation, "observation")["kind"]))) {
        return check("closed-vocabulary", false, `outcome '${String(outcome["runId"])}' invents a failure kind`);
      }
    }
    const failure = outcome["normalizedFailure"];
    if (failure !== null && failure !== undefined && !vocabulary.has(String(asRecord(failure, "failure")["kind"]))) {
      return check("closed-vocabulary", false, `outcome '${String(outcome["runId"])}' invents a normalized failure kind`);
    }
  }
  for (const variant of variants) {
    for (const refusal of asArray(variant["promotionRefusalKinds"], "promotionRefusalKinds")) {
      if (!vocabulary.has(String(refusal))) {
        return check("closed-vocabulary", false, "a promotion refusal invents a failure kind");
      }
    }
  }
  for (const comparison of comparisons) {
    for (const row of asArray(comparison["rows"], "rows")) {
      for (const kind of Object.keys(asRecord(asRecord(row, "row")["failureKindCounts"], "counts"))) {
        if (!vocabulary.has(kind)) {
          return check("closed-vocabulary", false, "a comparison row invents a failure kind");
        }
      }
    }
  }
  return check("closed-vocabulary", true, `${observationCount} failure observations, all within the closed vocabulary`);
}

/** 6. The comparability join + the metric deltas recompute from the outcomes alone. */
export function checkComparabilityJoin(): CheckResult {
  const { comparisons, runOutcomes } = loadExpectedOutcomes();
  if (comparisons.length !== 2) {
    return check("comparability-join", false, `expected 2 lane comparisons, got ${comparisons.length}`);
  }
  const lanes = comparisons.map((comparison) => String(comparison["lane"])).sort();
  if (lanes.join(",") !== "depth,reconstruction") {
    return check("comparability-join", false, "the lane comparisons must cover reconstruction + depth");
  }
  for (const comparison of comparisons) {
    const benchmarkId = String(comparison["benchmarkId"]);
    if (comparison["comparabilityKey"] !== `${benchmarkId}|${String(comparison["capability"])}`) {
      return check("comparability-join", false, "the comparability key is not benchmarkId|capability");
    }
    const rows = asArray(comparison["rows"], "rows").map((row) => asRecord(row, "row"));
    if (rows.length !== 2 || rows[0]?.["role"] !== "registered-candidate" || rows[1]?.["role"] !== "reference-path") {
      return check("comparability-join", false, "each lane comparison must join the candidate with the reference path");
    }
    if (rows[0]?.["comparabilityKey"] !== comparison["comparabilityKey"] || rows[1]?.["comparabilityKey"] !== comparison["comparabilityKey"]) {
      return check("comparability-join", false, "the rows do not share the comparability key");
    }
    // the resource + uncertainty profiles ride along on every row:
    for (const row of rows) {
      const resource = asRecord(row["resourceProfile"], "resourceProfile");
      if (typeof resource["latencyMsP50"] !== "number" || typeof resource["memoryMiB"] !== "number") {
        return check("comparability-join", false, "a row is missing the declared latency/resource profile");
      }
      const uncertainty = asRecord(row["uncertaintyCharacteristics"], "uncertaintyCharacteristics");
      if (typeof uncertainty["calibration"] !== "string" || uncertainty["calibration"].length === 0) {
        return check("comparability-join", false, "a row is missing the uncertainty characteristics");
      }
    }
    // the metric deltas recompute from the outcomes alone (independent arithmetic):
    const lane = String(comparison["lane"]);
    const candidate = rows[0]!;
    const reference = rows[1]!;
    const candidateOutcomes = runOutcomes.filter(
      (outcome) => outcome["variant"] === candidate["variant"] && String(outcome["record"] && asRecord(outcome["record"], "record")["capability"]) === lane,
    );
    const referenceOutcomes = runOutcomes.filter(
      (outcome) => outcome["variant"] === reference["variant"] && String(asRecord(outcome["record"], "record")["capability"]) === lane,
    );
    const sharedTaskIds = asArray(comparison["sharedContentTaskIds"], "sharedContentTaskIds").map(String);
    if (sharedTaskIds.length === 0) {
      return check("comparability-join", false, `the ${lane} lane shares no content tasks`);
    }
    for (const delta of asArray(comparison["metricDeltas"], "metricDeltas")) {
      const entry = asRecord(delta, "delta");
      const taskId = String(entry["taskId"]);
      if (!sharedTaskIds.includes(taskId)) {
        return check("comparability-join", false, `a metric delta references non-shared task '${taskId}'`);
      }
      const metric = String(entry["metric"]);
      const meanAbs = (outcomes: readonly Json[]): number => {
        const found = outcomes.find((outcome) => String(outcome["taskId"]) === taskId);
        if (found === undefined) {
          return Number.NaN;
        }
        const values = asArray(asRecord(found["record"], "record")["metrics"], "metrics")
          .map((metricEntry) => asRecord(metricEntry, "metric"))
          .filter((metricEntry) => String(metricEntry["metric"]) === metric)
          .map((metricEntry) => Math.abs(Number(metricEntry["value"])));
        return values.reduce((sum, value) => sum + value, 0) / values.length;
      };
      const ma = meanAbs(candidateOutcomes);
      const ref = meanAbs(referenceOutcomes);
      if (!Number.isFinite(ma) || !Number.isFinite(ref)) {
        return check("comparability-join", false, `the ${lane}/${taskId}/${metric} delta does not recompute (missing metric)`);
      }
      if (Math.abs(Number(entry["mapAnythingMeanAbs"]) - ma) > 1e-12 || Math.abs(Number(entry["referenceMeanAbs"]) - ref) > 1e-12) {
        return check("comparability-join", false, `the ${lane}/${taskId}/${metric} means do not recompute from the outcomes`);
      }
      if (Math.abs(Number(entry["delta"]) - (ma - ref)) > 1e-12) {
        return check("comparability-join", false, `the ${lane}/${taskId}/${metric} delta does not recompute`);
      }
    }
  }
  // the reconstruction-lane deltas are EXACTLY 0; the depth-lane deltas are non-zero (the documented deviation):
  const reconstruction = comparisons.find((comparison) => comparison["lane"] === "reconstruction")!;
  for (const delta of asArray(reconstruction["metricDeltas"], "metricDeltas")) {
    if (Number(asRecord(delta, "delta")["delta"]) !== 0) {
      return check("comparability-join", false, "the reconstruction-lane deltas must be exactly 0 (the shared deterministic core)");
    }
  }
  const depth = comparisons.find((comparison) => comparison["lane"] === "depth")!;
  const depthMae = asArray(depth["aggregateDeltas"], "aggregateDeltas")
    .map((entry) => asRecord(entry, "entry"))
    .find((entry) => entry["metric"] === "depth_mae_m");
  if (depthMae === undefined || Number(depthMae["delta"]) <= 0) {
    return check("comparability-join", false, "the depth-lane mae delta must be non-zero (the documented deviation)");
  }
  return check(
    "comparability-join",
    true,
    "2 lane comparisons joined on benchmarkId|capability; the metric deltas recompute from the outcomes alone (reconstruction deltas exactly 0; the depth delta is the documented deviation)",
  );
}

/** 7. The lawful registry lifecycle (as committed data). */
export function checkRegistryLifecycle(): CheckResult {
  const { registryLog, variants } = loadExpectedOutcomes();
  const kinds = registryLog.map((event) => String(event["kind"]));
  // the head: 3 registrations + 3 evaluation-starts:
  const head = kinds.slice(0, 6);
  const expectedHead = ["provider-registered", "provider-registered", "provider-registered", "evaluation-started", "evaluation-started", "evaluation-started"];
  if (head.join(",") !== expectedHead.join(",")) {
    return check("registry-lifecycle", false, "the log head is not 3 registrations + 3 evaluation-starts");
  }
  // the whole log: 12 execution-normalized + 16 provenance-sealed (12 per-run + 4 consolidated)
  // + 3 single-shot benchmark-recorded intakes + EXACTLY ONE promotion decision:
  const executions = kinds.filter((kind) => kind === "execution-normalized").length;
  const seals = kinds.filter((kind) => kind === "provenance-sealed").length;
  const intakes = kinds.filter((kind) => kind === "benchmark-recorded").length;
  const decisions = kinds.filter((kind) => kind === "promotion-decided").length;
  if (executions !== 12) {
    return check("registry-lifecycle", false, `expected 12 execution-normalized events, got ${executions}`);
  }
  if (seals !== 16) {
    return check("registry-lifecycle", false, `expected 16 provenance-sealed events (12 per-run + 4 consolidated), got ${seals}`);
  }
  if (intakes !== 3) {
    return check("registry-lifecycle", false, `expected 3 benchmark-recorded intakes (the single-shot rule), got ${intakes}`);
  }
  if (decisions !== 1) {
    return check("registry-lifecycle", false, `expected exactly one promotion decision, got ${decisions}`);
  }
  // the promotion decision: the CANDIDATE's, REJECTED with the typed license-blocked refusal,
  // recorded AFTER the candidate's own benchmark intake + consolidated seals:
  const decisionIndex = kinds.findIndex((kind) => kind === "promotion-decided");
  const decision = asRecord(registryLog[decisionIndex]!, "decision");
  if (decision["providerId"] !== "mapanything") {
    return check("registry-lifecycle", false, "the promotion decision must belong to the registered candidate");
  }
  if (decision["decision"] !== "rejected") {
    return check("registry-lifecycle", false, "the candidate's promotion decision must be rejected");
  }
  const refusals = asArray(decision["refusals"], "refusals").map((refusal) => String(asRecord(refusal, "refusal")["kind"]));
  if (refusals.join(",") !== "license-blocked") {
    return check("registry-lifecycle", false, `the rejection must carry the typed license-blocked refusal (got [${refusals.join(", ")}])`);
  }
  if (kinds.slice(0, decisionIndex).filter((kind) => kind === "benchmark-recorded").length < 1) {
    return check("registry-lifecycle", false, "the candidate's decision must follow its benchmark intake");
  }
  // the candidate ends rejected; the reference entries are benchmarked (NO promotion for them):
  const candidate = variants.find((variant) => variant["variant"] === "mapanything");
  if (candidate?.["registryState"] !== "rejected") {
    return check("registry-lifecycle", false, "the candidate's committed registry state must be rejected");
  }
  if (asArray(candidate?.["promotionRefusalKinds"], "kinds").join(",") !== "license-blocked") {
    return check("registry-lifecycle", false, "the candidate's committed promotion refusals are wrong");
  }
  for (const variant of variants.filter((entry) => entry["variant"] !== "mapanything")) {
    if (variant["registryState"] !== "benchmarked") {
      return check("registry-lifecycle", false, `the reference entry '${String(variant["variant"])}' must end benchmarked (no promotion requested)`);
    }
    if (asArray(variant["promotionRefusalKinds"], "kinds").length !== 0) {
      return check("registry-lifecycle", false, "no promotion decision may exist for the reference entries");
    }
  }
  if (loadExpectedOutcomes().outcomes["replayEqual"] !== true) {
    return check("registry-lifecycle", false, "the committed replay proof is false");
  }
  return check(
    "registry-lifecycle",
    true,
    `${kinds.length} events: 3 registrations + 3 evaluation-starts + 12 (execution, seal) pairs + 3 single-shot intakes + 4 consolidated seals + the candidate's license-blocked rejection; replay equal`,
  );
}

/** 8. The summary recomputes (independent arithmetic over the outcomes). */
export function checkSummaryRecomputes(): CheckResult {
  const { runOutcomes } = loadExpectedOutcomes();
  const byCell: Record<string, number> = {};
  const byVariant: Record<string, number> = {};
  const byFailureKind: Record<string, number> = {};
  let expectedMatches = 0;
  for (const outcome of runOutcomes) {
    const cell = String(outcome["matrixCell"]);
    byCell[cell] = (byCell[cell] ?? 0) + 1;
    const variant = String(outcome["variant"]);
    byVariant[variant] = (byVariant[variant] ?? 0) + 1;
    if (outcome["expectedMatch"] === true) {
      expectedMatches += 1;
    }
    for (const kind of asArray(outcome["failureObservationKinds"], "kinds")) {
      const entry = String(kind);
      byFailureKind[entry] = (byFailureKind[entry] ?? 0) + 1;
    }
  }
  if (expectedMatches !== 12) {
    return check("summary-recomputes", false, `expected 12 expectedMatches, got ${expectedMatches}`);
  }
  if (byVariant["mapanything"] !== 8 || byVariant["reference-reconstruction"] !== 3 || byVariant["reference-depth"] !== 1) {
    return check("summary-recomputes", false, "the per-variant counts are wrong");
  }
  if (byFailureKind["unsupported-data"] !== 3 || byFailureKind["resource-exhaustion"] !== 1) {
    return check("summary-recomputes", false, "the failure-kind counts are wrong");
  }
  if ((byCell["grounded-pass"] ?? 0) !== 8) {
    return check("summary-recomputes", false, "the grounded-pass count must be 8 (4 MapAnything + 4 reference content runs)");
  }
  return check(
    "summary-recomputes",
    true,
    "12 outcomes: 8 grounded-pass (4 candidate + 4 reference), 2 degraded-evidence, 1 failed-invocation, 1 unsupported-task; refusal kinds {unsupported-data: 3, resource-exhaustion: 1}",
  );
}

/** 9. Both artifacts are committed in the canonical form (byte-stable). */
export function checkCanonicalForm(): CheckResult {
  for (const path of [SCENARIO_PATH, OUTCOMES_PATH]) {
    const committed = readFileSync(path, "utf8");
    if (committed !== canonicalJson(JSON.parse(committed))) {
      return check("canonical-form", false, `${path} is not canonical (sorted keys, 2-space indent, trailing newline)`);
    }
  }
  return check("canonical-form", true, "both committed artifacts are canonical JSON (byte-stable)");
}

