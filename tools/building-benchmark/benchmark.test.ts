/** The engine's DOCUMENTED formula table (quantity-models.ts), recomputed here. */
function parameterOf(spec: OperationSpecView, name: string): number {
  const parameter = spec.parameters.find((entry) => entry.name === name);
  if (parameter === undefined || typeof parameter.value !== "number") {
    throw new Error(`scenario parameter '${name}' is missing or non-numeric`);
  }
  return parameter.value;
}

