interface Json {
  readonly [key: string]: unknown;
}

function asRecord(value: unknown, label: string): Json {
  if (typeof value !== "object" || value === null || Array.isArray(value)) {
    throw new Error(`${label}: expected a JSON object`);
  }
  return value as Json;
}

function asArray(value: unknown, label: string): readonly unknown[] {
  if (!Array.isArray(value)) {
    throw new Error(`${label}: expected a JSON array`);
  }
  return value;
}

export interface CommittedScenarioSet {
  readonly set: Json;
  readonly scenarios: readonly Json[];
  readonly providers: readonly Json[];
}

export function loadScenarioSet(): CommittedScenarioSet {
  const set = asRecord(readJson(SCENARIO_PATH), "scenario set");
  return {
    set,
    scenarios: asArray(set["scenarios"], "scenarios").map((entry) =>
      asRecord(entry, "scenario"),
    ),
    providers: asArray(set["providers"], "providers").map((entry) =>
      asRecord(entry, "provider"),
    ),
  };
}

export interface CommittedOutcomes {
  readonly outcomes: Json;
  readonly evaluations: readonly Json[];
  readonly registryLog: readonly Json[];
}

export function loadExpectedOutcomes(): CommittedOutcomes {
  const outcomes = asRecord(readJson(OUTCOMES_PATH), "expected outcomes");
  return {
    outcomes,
    evaluations: asArray(outcomes["evaluations"], "evaluations").map((entry) =>
      asRecord(entry, "evaluation"),
    ),
    registryLog: asArray(outcomes["registryLog"], "registryLog").map((entry) =>
      asRecord(entry, "event"),
    ),
  };
}

/* ------------------------------------------------------------------ */
/* The checks (pure; every check answers a typed verdict)               */
/* ------------------------------------------------------------------ */

export interface CheckResult {
  readonly check: string;
  readonly ok: boolean;
  readonly detail: string;
}

function check(check: string, ok: boolean, detail: string): CheckResult {
  return { check, ok, detail };
}

/** 1a. The scenario set's typed seal + pinned benchmark ids per scenario. */
export function checkScenarioSetSeal(): CheckResult {
  const { set, scenarios } = loadScenarioSet();
  if (set["kind"] !== "reality-eval-scenario-set") {
    return check("scenario-set-seal", false, `wrong typed seal '${String(set["kind"])}`);
  }
  if (set["schemaVersion"] !== "reality-eval-scenario-set/1") {
    return check("scenario-set-seal", false, "wrong schema version");
  }
  for (const scenario of scenarios) {
    if (scenario["kind"] !== "reality-eval-scenario") {
      return check("scenario-set-seal", false, "a scenario carries the wrong seal");
    }
    const capability = String(scenario["capability"]);
    const expectedBenchmark = LANE_BENCHMARK_IDS[capability];
    if (expectedBenchmark === undefined) {
      return check("scenario-set-seal", false, `unknown capability '${capability}'`);
    }
    if (scenario["benchmarkId"] !== expectedBenchmark) {
      return check(
        "scenario-set-seal",
        false,
        `scenario '${String(scenario["scenarioId"])}' benchmarkId is not the pinned '${expectedBenchmark}'`,
      );
    }
  }
  return check(
    "scenario-set-seal",
    true,
    `${scenarios.length} scenarios sealed, every benchmarkId pinned per capability`,
  );
}

/** 1b. The golden outcomes reference the scenario set by its content digest. */
export function checkScenarioSetDigest(): CheckResult {
  const { set } = loadScenarioSet();
  const { outcomes } = loadExpectedOutcomes();
  const digest = digestOf(set);
  if (outcomes["scenarioSetDigest"] !== digest) {
    return check(
      "scenario-set-digest",
      false,
      `expected ${digest}, committed ${String(outcomes["scenarioSetDigest"])}`,
    );
  }
  return check("scenario-set-digest", true, digest);
}

/**
 * 1c. Content addressing: every committed record's `recordId` re-derives
 * from its own semantic projection (the control plane's identity input:
 * kind, provider, benchmark, capability, metrics, failure observations,
 * resource observations, reproduction — never a hand-numbered id).
 */
export function checkRecordContentAddressing(): CheckResult {
  const { evaluations } = loadExpectedOutcomes();
  for (const evaluation of evaluations) {
    const record = asRecord(evaluation["record"], "record");
    const { recordId, ...rest } = record;
    const identityInput = {
      kind: "provider-benchmark-record",
      providerId: rest["providerId"],
      technologyVersion: rest["technologyVersion"],
      benchmarkId: rest["benchmarkId"],
      capability: rest["capability"],
      metrics: rest["metrics"],
      failureObservations: rest["failureObservations"],
      resourceObservations: rest["resourceObservations"],
      reproduction: rest["reproduction"],
    };
    const derived = digestOf(identityInput);
    if (recordId !== derived) {
      return check(
        "record-content-addressing",
        false,
        `evaluation '${String(evaluation["scenarioId"])}': recordId ${String(recordId)} != derived ${derived}`,
      );
    }
  }
  return check(
    "record-content-addressing",
    true,
    `${evaluations.length} records re-derive their content addresses`,
  );
}

/** 1d. Every manifest's `manifestId` re-derives (portability by digest). */
export function checkManifestContentAddressing(): CheckResult {
  const { evaluations } = loadExpectedOutcomes();
  for (const evaluation of evaluations) {
    const manifest = asRecord(evaluation["manifest"], "manifest");
    const { manifestId, ...rest } = manifest;
    const derived = digestOf(rest);
    if (manifestId !== derived) {
      return check(
        "manifest-content-addressing",
        false,
        `evaluation '${String(evaluation["scenarioId"])}': manifestId ${String(manifestId)} != derived ${derived}`,
      );
    }
    // the manifest chains its record 1:1 (reference + digest)
    const references = asArray(manifest["benchmarkRecordReferences"], "references");
    const digests = asArray(manifest["benchmarkRecordDigests"], "digests");
    const record = asRecord(evaluation["record"], "record");
    if (references.length !== 1 || digests.length !== 1) {
      return check("manifest-content-addressing", false, "a manifest must chain exactly one record");
    }
    if (references[0] !== record["recordId"]) {
      return check(
        "manifest-content-addressing",
        false,
        `the manifest's record reference does not match the evaluation's record`,
      );
    }
    const recordDigest = digestOf(record);
    if (digests[0] !== recordDigest) {
      return check(
        "manifest-content-addressing",
        false,
        `the manifest's record digest does not re-derive from the record`,
      );
    }
  }
  return check(
    "manifest-content-addressing",
    true,
    `${evaluations.length} manifests re-derive and chain their records`,
  );
}

/** 1e. Every input digest re-derives from the scenario's own input fixture. */
export function checkInputDigests(): CheckResult {
  const { scenarios } = loadScenarioSet();
  const { evaluations } = loadExpectedOutcomes();
  const inputDigestOf = (input: Json): string =>
    digestOf({
      kind: "provider-input",
      capability: input["capability"],
      payload: input["payload"],
    });
  const digestByScenarioId = new Map(
    scenarios.map((scenario) => [String(scenario["scenarioId"]), inputDigestOf(asRecord(scenario["input"], "input"))]),
  );
  for (const evaluation of evaluations) {
    const scenarioId = String(evaluation["scenarioId"]);
    const record = asRecord(evaluation["record"], "record");
    const reproduction = asRecord(record["reproduction"], "reproduction");
    const expected = digestByScenarioId.get(scenarioId);
    if (expected === undefined) {
      return check("input-digests", false, `no committed scenario '${scenarioId}'`);
    }
    if (reproduction["inputsDigest"] !== expected) {
      return check(
        "input-digests",
        false,
        `evaluation '${scenarioId}': the reproduction inputsDigest does not re-derive from the scenario's input fixture`,
      );
    }
  }
  return check("input-digests", true, `${evaluations.length} input digests re-derive`);
}

/** 2. The closed failure vocabulary (no invented failure kinds). */
export function checkClosedVocabulary(): CheckResult {
  const vocabulary = new Set<string>(CLOSED_FAILURE_KINDS);
  const { evaluations } = loadExpectedOutcomes();
  let observationCount = 0;
  for (const evaluation of evaluations) {
    const record = asRecord(evaluation["record"], "record");
    for (const observation of asArray(record["failureObservations"], "failureObservations")) {
      const entry = asRecord(observation, "observation");
      observationCount += 1;
      if (!vocabulary.has(String(entry["kind"]))) {
        return check(
          "closed-vocabulary",
          false,
          `evaluation '${String(evaluation["scenarioId"])}' invents failure kind '${String(entry["kind"])}'`,
        );
      }
    }
    const kinds = asArray(evaluation["failureObservationKinds"], "failureObservationKinds");
    if (kinds.length !== asArray(record["failureObservations"], "failureObservations").length) {
      return check(
        "closed-vocabulary",
        false,
        `evaluation '${String(evaluation["scenarioId"])}': the projected kinds do not match the record's observations`,
      );
    }
  }
  return check(
    "closed-vocabulary",
    true,
    `${observationCount} failure observations, all within the closed vocabulary`,
  );
}

/** 3. The class doctrine (the day-27 rule over the committed goldens). */
export function checkClassDoctrine(): CheckResult {
  const { evaluations } = loadExpectedOutcomes();
  let positives = 0;
  let negatives = 0;
  let discriminations = 0;
  for (const evaluation of evaluations) {
    const scenarioClass = String(evaluation["scenarioClass"]);
    const verdict = String(evaluation["verdict"]);
    const kinds = asArray(evaluation["failureObservationKinds"], "kinds").map(String);
    if (scenarioClass === "positive") {
      positives += 1;
      if (verdict !== "pass" || kinds.length > 0) {
        return check(
          "class-doctrine",
          false,
          `positive scenario '${String(evaluation["scenarioId"])}' must pass with zero observations`,
        );
      }
    } else if (scenarioClass === "negative") {
      negatives += 1;
      if (verdict !== "pass" || kinds.length === 0) {
        return check(
          "class-doctrine",
          false,
          `negative scenario '${String(evaluation["scenarioId"])}' must pass as explicit-and-safe with its expected refusal recorded`,
        );
      }
    } else if (scenarioClass === "discrimination") {
      discriminations += 1;
      if (verdict !== "fail" || !kinds.includes("perception-failure") || evaluation["discriminationCaught"] !== true) {
        return check(
          "class-doctrine",
          false,
          `discrimination scenario '${String(evaluation["scenarioId"])}' MUST be caught: verdict fail + recorded perception-failure observations (the harness records the failure, not just low scores)`,
        );
      }
    } else {
      return check("class-doctrine", false, `unknown scenario class '${scenarioClass}'`);
    }
  }
  if (positives === 0 || negatives === 0 || discriminations === 0) {
    return check(
      "class-doctrine",
      false,
      "the committed suite must cover all three classes (positive / negative / discrimination)",
    );
  }
  return check(
    "class-doctrine",
    true,
    `${positives} positive / ${negatives} negative / ${discriminations} discrimination — the discrimination is CAUGHT with recorded observations`,
  );
}

/** 4. Scenario ↔ record coherence + comparability within pinned lanes. */
export function checkScenarioRecordCoherence(): CheckResult {
  const { scenarios } = loadScenarioSet();
  const { evaluations } = loadExpectedOutcomes();
  const byId = new Map(scenarios.map((scenario) => [String(scenario["scenarioId"]), scenario]));
  const comparabilityKeys = new Set<string>();
  for (const evaluation of evaluations) {
    const scenarioId = String(evaluation["scenarioId"]);
    const scenario = byId.get(scenarioId);
    if (scenario === undefined) {
      return check("scenario-record-coherence", false, `no committed scenario '${scenarioId}'`);
    }
    const record = asRecord(evaluation["record"], "record");
    const reference = asRecord(scenario["providerReference"], "providerReference");
    if (record["providerId"] !== reference["providerId"]) {
      return check("scenario-record-coherence", false, `${scenarioId}: providerId mismatch`);
    }
    if (record["technologyVersion"] !== reference["technologyVersion"]) {
      return check("scenario-record-coherence", false, `${scenarioId}: technologyVersion mismatch`);
    }
    if (record["capability"] !== scenario["capability"]) {
      return check("scenario-record-coherence", false, `${scenarioId}: capability mismatch`);
    }
    if (record["benchmarkId"] !== scenario["benchmarkId"]) {
      return check("scenario-record-coherence", false, `${scenarioId}: benchmarkId mismatch`);
    }
    const metrics = asArray(record["metrics"], "metrics");
    if (metrics.length === 0) {
      return check(
        "scenario-record-coherence",
        false,
        `${scenarioId}: a record is never silent (at least one metric required)`,
      );
    }
    for (const metric of metrics) {
      const entry = asRecord(metric, "metric");
      const value = entry["value"];
      if (typeof value !== "number" || !Number.isFinite(value)) {
        return check("scenario-record-coherence", false, `${scenarioId}: non-finite metric value`);
      }
    }
    comparabilityKeys.add(`${String(record["benchmarkId"])}|${String(record["capability"])}`);
  }
  if (comparabilityKeys.size !== 2) {
    return check(
      "scenario-record-coherence",
      false,
      `expected exactly 2 comparability keys (one per pinned lane), got ${comparabilityKeys.size}`,
    );
  }
  return check(
    "scenario-record-coherence",
    true,
    `${evaluations.length} evaluations coherent with their scenarios; comparability keys: [${[...comparabilityKeys].sort().join(", ")}]`,
  );
}

/** 5. The lawful registry lifecycle order (as committed data). */
export function checkRegistryLifecycle(): CheckResult {
  const { outcomes, registryLog, evaluations } = loadExpectedOutcomes();
  const providerCount = asArray(
    asRecord(loadScenarioSet().set, "set")["providers"],
    "providers",
  ).length;
  const kinds = registryLog.map((event) => String(event["kind"]));
  // the head: every provider registered, then every provider evaluation-started
  const head = kinds.slice(0, providerCount * 2);
  const expectedHead = [
    ...new Array<string>(providerCount).fill("provider-registered"),
    ...new Array<string>(providerCount).fill("evaluation-started"),
  ];
  if (head.join(",") !== expectedHead.join(",")) {
    return check("registry-lifecycle", false, `the log head is not register + evaluation-started`);
  }
  // the body: per evaluation, execution-normalized → provenance-sealed
  const body = kinds.slice(providerCount * 2);
  if (body.length !== evaluations.length * 2) {
    return check(
      "registry-lifecycle",
      false,
      `expected ${evaluations.length * 2} lifecycle events (2 per scenario), got ${body.length}`,
    );
  }
  for (let index = 0; index < body.length; index += 2) {
    if (body[index] !== "execution-normalized" || body[index + 1] !== "provenance-sealed") {
      return check(
        "registry-lifecycle",
        false,
        `lifecycle event pair ${index} is not (execution-normalized, provenance-sealed)`,
      );
    }
  }
  // NO self-promotion: the suite ends at provenance-sealed
  if (kinds.includes("promotion-decided") || kinds.includes("benchmark-recorded")) {
    return check(
      "registry-lifecycle",
      false,
      "the evaluation suite never self-promotes (no promotion-decided / benchmark-recorded events)",
    );
  }
  // every sealed manifest id appears in the log
  const sealedIds = new Set(
    registryLog
      .filter((event) => event["kind"] === "provenance-sealed")
      .map((event) => String(asRecord(event["manifest"], "manifest")["manifestId"])),
  );
  for (const evaluation of evaluations) {
    const manifest = asRecord(evaluation["manifest"], "manifest");
    if (!sealedIds.has(String(manifest["manifestId"]))) {
      return check(
        "registry-lifecycle",
        false,
        `evaluation '${String(evaluation["scenarioId"])}': its manifest is not sealed in the committed log`,
      );
    }
  }
  const suiteId = String(outcomes["suiteId"]);
  return check(
    "registry-lifecycle",
    true,
    `${kinds.length} events: ${providerCount} registrations + ${providerCount} evaluation-starts + ${evaluations.length} (execution-normalized, provenance-sealed) pairs — suite ${suiteId} ends at provenance-sealed`,
  );
}

/** Runs EVERY check (the gate pickup's full sweep). */
export function runAllChecks(): readonly CheckResult[] {
  return [
    checkScenarioSetSeal(),
    checkScenarioSetDigest(),
    checkRecordContentAddressing(),
    checkManifestContentAddressing(),
    checkInputDigests(),
    checkClosedVocabulary(),
    checkClassDoctrine(),
    checkScenarioRecordCoherence(),
    checkRegistryLifecycle(),
  ];
}
