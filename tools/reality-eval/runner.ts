/** The closed failure vocabulary (frozen reference data — 9 kinds). */
export const CLOSED_FAILURE_KINDS = [
  "perception-failure",
  "retrieval-failure",
  "reasoning-failure",
  "unsupported-data",
  "operation-semantic-failure",
  "resource-exhaustion",
  "timeout",
  "license-blocked",
  "contract-mismatch",
] as const;

/** The pinned Layer-1 benchmark id per capability (the lane table). */
export const LANE_BENCHMARK_IDS: Readonly<Record<string, string>> = {
  reconstruction: "reality-eval-reconstruction/1",
  depth: "reality-eval-depth/1",
  "capture-readiness": "reality-eval-capture-readiness/1",
  retrieval: "reality-eval-retrieval/1",
};

