/**
 * PROD-027 — the Layer-1 evaluation benchmark CHECK RUNNER (the tools/
 * side — the building-benchmark / competitive-parity convention).
 *
 * Wired into the root `bun run verify` (this directory's benchmark.test.ts
 * is a tools/ test, picked up by the root `bun test` like
 * tools/building-benchmark/benchmark.test.ts).
 *
 * The boundary matrix forbids tools → backend/packages imports, so this
 * runner consumes the COMMITTED ARTIFACTS AS DATA (pure reads + pure
 * arithmetic — no harness import): the committed scenario set
 * (`tools/reality-eval/scenario.json`) and the committed golden outcomes
 * (`fixtures/expected-outcomes.json`, regenerated by
 * `bun backend/api/src/reality-eval/regenerate.ts` where the harness CAN be
 * imported). The LIVE byte-for-byte reproduction leg lives in
 * `backend/api/src/reality-eval/golden.test.ts` (the backend zone) for the
 * same boundary reason.
 *
 * What this runner proves over the committed data:
 *
 *  1. COHERENCE — the scenario set's typed seal, the suite digest
 *     re-derives (sha-256 over the canonical JSON — sorted keys, 2-space
 *     indent, trailing newline, the shared wire canonicalization), every
 *     committed record's `recordId` re-derives from its own content (the
 *     control plane's content addressing), every manifest's `manifestId`
 *     re-derives, and every input digest re-derives from the scenario's
 *     own input fixture;
 *  2. THE CLOSED FAILURE VOCABULARY — no committed observation invents a
 *     failure kind;
 *  3. THE CLASS DOCTRINE (the day-27 rule) — the discrimination scenario
 *     is CAUGHT (verdict fail + RECORDED perception-failure observations —
 *     not just low scores); the negative scenarios are explicit-and-safe;
 *     the positives pass with zero observations;
 *  4. SCENARIO ↔ RECORD COHERENCE — provider identity, capability, pinned
 *     benchmark and input digest agree; the records form comparable rows
 *     (benchmarkId | capability) within their pinned lanes;
 *  5. THE LAWFUL REGISTRY LIFECYCLE — the committed event log is the
 *     evaluation lifecycle in order (register → evaluation-started → per
 *     scenario: execution-normalized → provenance-sealed) with NO
 *     self-promotion (promotion is the control plane's governed decision).
 *
 * Determinism: pure reads of committed files + pure arithmetic; no clock,
 * no randomness, no network, no engine import.
 */

import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";

const SCENARIO_PATH = resolve(import.meta.dir, "scenario.json");
const OUTCOMES_PATH = resolve(import.meta.dir, "fixtures", "expected-outcomes.json");

/* ------------------------------------------------------------------ */
/* The canonical form (the generic discipline — no package imports)     */
/* ------------------------------------------------------------------ */

/** Sort one parsed JSON value's object keys recursively (arrays keep order). */
function sortValue(value: unknown): unknown {
  if (Array.isArray(value)) {
    return value.map(sortValue);
  }
  if (value !== null && typeof value === "object") {
    const record = value as Record<string, unknown>;
    const out: Record<string, unknown> = {};
    for (const key of Object.keys(record).sort()) {
      out[key] = sortValue(record[key]);
    }
    return out;
  }
  return value;
}

/** Canonical JSON text: 2-space indented, sorted keys, trailing newline. */
function canonicalJson(value: unknown): string {
  return `${JSON.stringify(sortValue(value), null, 2)}\n`;
}

function sha256Hex(text: string): string {
  return createHash("sha256").update(text, "utf8").digest("hex");
}

/** sha-256 over the canonical JSON (the shared wire canonicalization). */
function digestOf(value: unknown): string {
  return sha256Hex(canonicalJson(value));
}

function readJson(path: string): unknown {
  return JSON.parse(readFileSync(path, "utf8")) as unknown;
}

