export interface EquivalenceArtifactCheck {
  readonly id: string;
  readonly passed: boolean;
  readonly detail: string;
}

export interface EquivalenceArtifactReport {
  readonly ok: boolean;
  readonly checks: readonly EquivalenceArtifactCheck[];
  readonly summary: {
    readonly total: number;
    readonly byExpectation: Readonly<Record<string, number>>;
    readonly byObserved: Readonly<Record<string, number>>;
    readonly expectationMatches: number;
    readonly refusalTaxonomyCoverage: readonly string[];
    readonly clarificationSlotCoverage: readonly string[];
    readonly provenanceOnlyControlVerdict: string;
    readonly provenanceManifestDigest: string;
    readonly benchmarkRecordDigest: string;
  };
}

/**
 * Verifies the committed HFX-301 artifacts (pure; every check is named,
 * deterministic and listed in the module header).
 */
export function verifyEquivalenceArtifacts(): EquivalenceArtifactReport {
  const { scenarioSuite, pairs, outcomesSuite, outcomes } = loadEquivalenceArtifacts();
  const checks: EquivalenceArtifactCheck[] = [];
  const check = (id: string, passed: boolean, detail: string): void => {
    checks.push({ id, passed, detail });
  };
  const pairOf = (pairId: string): PairView => {
    const found = pairs.find((pair) => pair.pairId === pairId);
    if (found === undefined) {
      throw new Error(`runner: no committed pair for '${pairId}'`);
    }
    return found;
  };
  const outcomeOf = (pairId: string): OutcomeView => {
    const found = outcomes.find((outcome) => outcome.pairId === pairId);
    if (found === undefined) {
      throw new Error(`runner: no committed outcome for '${pairId}'`);
    }
    return found;
  };

  /* 1. Coherence ---------------------------------------------------- */

  const suiteId = String(scenarioSuite["suiteId"] ?? "");
  const scenarioPins = asRecord(scenarioSuite["pins"], "scenario.pins");
  const outcomesPins = asRecord(outcomesSuite["pins"], "outcomes.pins");
  check(
    "coherence-suite-identity",
    suiteId === "equivalence-eval-suite/1" &&
      String(outcomesSuite["suiteId"] ?? "") === suiteId &&
      String(scenarioSuite["benchmarkId"] ?? "") === "equivalence-eval-suite/1" &&
      String(outcomesSuite["benchmarkId"] ?? "") === "equivalence-eval-suite/1" &&
      String(scenarioSuite["version"] ?? "") === "1.0.0" &&
      String(scenarioSuite["codeVersion"] ?? "") === "hfx-301/equivalence-eval/1" &&
      String(outcomesSuite["codeVersion"] ?? "") === "hfx-301/equivalence-eval/1",
    `both artifacts pin suiteId '${suiteId}', benchmarkId 'equivalence-eval-suite/1', version '1.0.0', codeVersion 'hfx-301/equivalence-eval/1'`,
  );
  const pairIds = pairs.map((pair) => pair.pairId);
  check(
    "coherence-pair-identity",
    new Set(pairIds).size === pairIds.length && pairIds.length === 33,
    `${pairIds.length} pairs with unique ids (16 equivalent + 4 declared-different + 7 agent-refused + 6 agent-clarification)`,
  );
  const outcomeIds = outcomes.map((outcome) => outcome.pairId);
  check(
    "coherence-outcome-alignment",
    outcomeIds.length === pairIds.length &&
      pairIds.every((id) => outcomeIds.includes(id)) &&
      outcomeIds.every((id) => pairIds.includes(id)) &&
      Number(outcomesSuite["pairCount"] ?? -1) === outcomes.length,
    "the outcome ids align 1:1 with the pair ids",
  );
  check(
    "coherence-canonical-form",
    canonicalJson(readJson(SCENARIO_PATH)) === readFileSync(SCENARIO_PATH, "utf8") &&
      canonicalJson(readJson(OUTCOMES_PATH)) === readFileSync(OUTCOMES_PATH, "utf8"),
    "both committed artifacts are canonical JSON (sorted keys, 2-space, trailing newline)",
  );
  const pinsEqual =
    scenarioPins["taxonomyVersion"] === outcomesPins["taxonomyVersion"] &&
    scenarioPins["compilerCodeVersion"] === outcomesPins["compilerCodeVersion"] &&
    scenarioPins["engineKind"] === outcomesPins["engineKind"] &&
    scenarioPins["engineCodeVersion"] === outcomesPins["engineCodeVersion"] &&
    scenarioPins["corpusDigest"] === outcomesPins["corpusDigest"];
  const digestShape = /^[0-9a-f]{64}$/;
  check(
    "coherence-version-pins",
    pinsEqual &&
      String(scenarioPins["taxonomyVersion"] ?? "") ===
        "prod-023/refusal-and-operation-taxonomy/1" &&
      String(scenarioPins["compilerCodeVersion"] ?? "") === "prod-023/deterministic-grammar/1" &&
      String(scenarioPins["engineKind"] ?? "") === "aise-solution-engine" &&
      String(scenarioPins["engineCodeVersion"] ?? "") === "1.0.0" &&
      digestShape.test(String(scenarioPins["corpusDigest"] ?? "")),
    "the version-pinned manifest header (taxonomy, engine kind+version, compiler, corpus digest) rides both artifacts identically",
  );

  /* 2. The four-cell behavior matrix ------------------------------- */

  const byExpectation: Record<string, number> = {};
  for (const pair of pairs) {
    byExpectation[pair.expectation] = (byExpectation[pair.expectation] ?? 0) + 1;
  }
  const missingCells = EQUIVALENCE_CELLS.filter((cell) => (byExpectation[cell] ?? 0) === 0);
  check(
    "matrix-four-cells-present",
    missingCells.length === 0,
    missingCells.length === 0
      ? "all four behavior-matrix cells carry committed pairs (16/4/7/6)"
      : `missing cells: ${missingCells.join(", ")}`,
  );
  const expectationMismatches = outcomes.filter((outcome) => !outcome.expectationMet);
  check(
    "matrix-expectation-gate",
    expectationMismatches.length === 0,
    expectationMismatches.length === 0
      ? "every committed outcome's observed cell (and declared kind) satisfies its pair's expectation"
      : `mismatches: ${expectationMismatches.map((outcome) => outcome.pairId).join(", ")}`,
  );
  const declaredWithoutKind = outcomes.filter(
    (outcome) => outcome.expectation === "declared-different" && outcome.differenceKind === undefined,
  );
  check(
    "matrix-declared-kind-required",
    declaredWithoutKind.length === 0,
    "every declared-different outcome records its difference kind (declared, never discovered)",
  );

  /* 3. The equivalence proof ---------------------------------------- */

  const equivalents = outcomes.filter((outcome) => outcome.observed === "equivalent");
  const notCleanEquivalents = equivalents.filter(
    (outcome) =>
      outcome.comparisonVerdict !== "equivalent" ||
      (outcome.equalPoints ?? 0) !== COMPARISON_POINT_KINDS.length ||
      (outcome.divergentPoints?.length ?? 0) !== 0,
  );
  check(
    "equivalence-canonical-identity",
    notCleanEquivalents.length === 0,
    notCleanEquivalents.length === 0
      ? `all ${equivalents.length} equivalent pairs carry ZERO divergent points over the four canonical journey points (identity semantics, state digest, validation verdict, BOQ delta)`
      : `unclean equivalences: ${notCleanEquivalents.map((outcome) => outcome.pairId).join(", ")}`,
  );
  const journeysNotApplied = equivalents.filter(
    (outcome) =>
      outcome.agentCompileKind !== "operation-intent" ||
      outcome.directApplicationOutcome !== "applied",
  );
  check(
    "equivalence-both-paths-executed",
    journeysNotApplied.length === 0,
    "every equivalent pair executed BOTH paths (compiled intent + direct journey applied)",
  );

  /* 4. The honest differences ---------------------------------------- */

  const declaredDifferent = outcomes.filter((outcome) => outcome.observed === "declared-different");
  const dishonestDifferences = declaredDifferent.filter(
    (outcome) =>
      (outcome.divergentPoints?.length ?? 0) === 0 ||
      outcome.differenceKind === undefined ||
      outcome.differenceKind !== outcomeOf(outcome.pairId).differenceKind ||
      !CLOSED_FAILURE_KINDS.includes(outcome.differenceKind ?? "") ||
      !outcome.differenceKinds?.every((kind) => CLOSED_FAILURE_KINDS.includes(kind)),
  );
  check(
    "differences-honest-and-declared",
    declaredDifferent.length === 4 && dishonestDifferences.length === 0,
    declaredDifferent.length === 4 && dishonestDifferences.length === 0
      ? "all 4 declared-different pairs carry ≥1 divergent point, record the closed-vocabulary kind and agree with their declaration — never hidden"
      : `dishonest differences: ${dishonestDifferences.map((outcome) => outcome.pairId).join(", ")}`,
  );
  const kindMismatches = declaredDifferent.filter((outcome) => {
    const pair = pairOf(outcome.pairId);
    return pair.expectation !== "declared-different";
  });
  check(
    "differences-match-corpus-declaration",
    kindMismatches.length === 0,
    "every declared-different outcome's pair declares the same cell in the committed corpus",
  );

  /* 5. The designed agent outcomes ---------------------------------- */

  const refusals = outcomes.filter((outcome) => outcome.observed === "agent-refused");
  const refusalGaps: string[] = [];
  for (const code of REFUSAL_REASON_CODES) {
    if (!refusals.some((outcome) => outcome.refusalReasonCode === code)) {
      refusalGaps.push(code);
    }
  }
  const refusalShapeViolations = refusals.filter(
    (outcome) =>
      outcome.agentCompileKind !== "unsafe-refusal" ||
      outcome.refusalReasonCode === undefined ||
      !REFUSAL_REASON_CODES.includes(outcome.refusalReasonCode),
  );
  check(
    "designed-refusal-taxonomy",
    refusals.length === 7 && refusalGaps.length === 0 && refusalShapeViolations.length === 0,
    refusals.length === 7 && refusalGaps.length === 0 && refusalShapeViolations.length === 0
      ? "all 7 unsafe-taxonomy reason codes are exhibited with NO agent journey — the refusals are designed outcomes, never equivalence failures"
      : `gaps: ${[...refusalGaps, ...refusalShapeViolations.map((o) => o.pairId)].join(", ")}`,
  );
  const clarifications = outcomes.filter((outcome) => outcome.observed === "agent-clarification");
  const clarificationGaps: string[] = [];
  for (const slot of CLARIFICATION_SLOT_KINDS) {
    if (!clarifications.some((outcome) => outcome.clarificationSlots?.includes(slot))) {
      clarificationGaps.push(slot);
    }
  }
  const clarificationShapeViolations = clarifications.filter(
    (outcome) => outcome.agentCompileKind !== "clarification-needed",
  );
  check(
    "designed-clarification-slots",
    clarifications.length === 6 &&
      clarificationGaps.length === 0 &&
      clarificationShapeViolations.length === 0,
    clarifications.length === 6 && clarificationGaps.length === 0 && clarificationShapeViolations.length === 0
      ? "all 5 clarification slot kinds are asked with targeted questions and NO agent journey"
      : `gaps: ${[...clarificationGaps, ...clarificationShapeViolations.map((o) => o.pairId)].join(", ")}`,
  );
  check(
    "designed-cells-direct-path-authored",
    [...refusals, ...clarifications].every(
      (outcome) => outcome.directApplicationOutcome === "applied",
    ),
    "every designed-outcome cell's direct path still authored (applied through the engine — the engine governs both equally)",
  );

  /* 6. The control-plane emission ----------------------------------- */

  const malformedArtifacts = outcomes.filter(
    (outcome) =>
      !digestShape.test(outcome.benchmarkRecordId) ||
      !digestShape.test(outcome.provenanceManifestId),
  );
  check(
    "emission-content-addressed",
    malformedArtifacts.length === 0,
    "every outcome carries 64-hex content-addressed record + manifest ids (the control-plane BenchmarkRecord + ProvenanceManifest)",
  );
  const committedSummary = asRecord(outcomesSuite["summary"], "summary");
  check(
    "emission-aggregate-digests",
    digestShape.test(String(committedSummary["provenanceManifestDigest"] ?? "")) &&
      digestShape.test(String(committedSummary["benchmarkRecordDigest"] ?? "")) &&
      String(committedSummary["provenanceOnlyControlVerdict"] ?? "") === "equivalent",
    "the aggregate digests are 64-hex and the provenance-only control verdict is 'equivalent' (the structural doctrine at journey level)",
  );

  /* 7. Summary recomputation (independent arithmetic) ---------------- */

  const byObserved: Record<string, number> = {};
  let expectationMatches = 0;
  for (const outcome of outcomes) {
    byObserved[outcome.observed] = (byObserved[outcome.observed] ?? 0) + 1;
    if (outcome.expectationMet) {
      expectationMatches += 1;
    }
  }
  const recomputedManifestDigest = sha256Hex(
    canonicalJson(outcomes.map((outcome) => outcome.provenanceManifestId)),
  );
  const recomputedRecordDigest = sha256Hex(
    canonicalJson(outcomes.map((outcome) => outcome.benchmarkRecordId)),
  );
  const committedByExpectation = committedSummary["byExpectation"] as Record<string, number>;
  const committedByObserved = committedSummary["byObserved"] as Record<string, number>;
  const summaryEqual =
    String(committedSummary["total"] ?? "") === String(outcomes.length) &&
    Object.entries(byExpectation).every(
      ([cell, count]) => (committedByExpectation?.[cell] ?? -1) === count,
    ) &&
    Object.entries(byObserved).every(
      ([cell, count]) => (committedByObserved?.[cell] ?? -1) === count,
    ) &&
    Number(committedSummary["expectationMatches"] ?? -1) === expectationMatches &&
    String(committedSummary["provenanceManifestDigest"] ?? "") === recomputedManifestDigest &&
    String(committedSummary["benchmarkRecordDigest"] ?? "") === recomputedRecordDigest;
  check(
    "summary-recomputes",
    summaryEqual,
    "the committed suite summary re-derives from the outcome rows alone (independent arithmetic incl. the ordered-manifest-id digest)",
  );

  /* 8. The corpus declaration consistency --------------------------- */

  const corpusMismatches = pairs.filter((pair) => {
    const outcome = outcomeOf(pair.pairId);
    return outcome.expectation !== pair.expectation;
  });
  check(
    "corpus-declaration-consistency",
    corpusMismatches.length === 0,
    "every committed pair's declared expectation matches its outcome's expectation",
  );

  const ok = checks.every((entry) => entry.passed);
  return {
    ok,
    checks,
    summary: {
      total: outcomes.length,
      byExpectation: Object.fromEntries(
        Object.entries(byExpectation).sort(([a], [b]) => a.localeCompare(b)),
      ),
      byObserved: Object.fromEntries(
        Object.entries(byObserved).sort(([a], [b]) => a.localeCompare(b)),
      ),
      expectationMatches,
      refusalTaxonomyCoverage: (committedSummary["refusalTaxonomyCoverage"] as string[]) ?? [],
      clarificationSlotCoverage: (committedSummary["clarificationSlotCoverage"] as string[]) ?? [],
      provenanceOnlyControlVerdict: String(committedSummary["provenanceOnlyControlVerdict"] ?? ""),
      provenanceManifestDigest: String(committedSummary["provenanceManifestDigest"] ?? ""),
      benchmarkRecordDigest: String(committedSummary["benchmarkRecordDigest"] ?? ""),
    },
  };
}

/* ------------------------------------------------------------------ */
/* The CLI entry (deterministic output; exit code is the gate)          */
/* ------------------------------------------------------------------ */

const isDirectRun =
  typeof process !== "undefined" &&
  typeof process.argv !== "undefined" &&
  process.argv[1] !== undefined &&
  resolve(process.argv[1]) === resolve(import.meta.path);

if (isDirectRun) {
  // The regeneration delegation: the boundary matrix forbids importing
  // the backend module from tools/, so --update-goldens SPAWNS the
  // backend-zone regeneration CLI (a pure subprocess boundary — the
  // committed artifacts are then rewritten deterministically).
  if (process.argv.includes("--update-goldens")) {
    const { spawnSync } = await import("node:child_process");
    const repoRoot = resolve(import.meta.dir, "..", "..");
    const result = spawnSync(
      process.execPath,
      ["backend/api/src/equivalence-eval/regenerate.ts"],
      { cwd: repoRoot, stdio: "inherit" },
    );
    if (result.status !== 0) {
      process.stdout.write("goldens update FAILED\n");
      process.exit(1);
    }
  }

  const report = verifyEquivalenceArtifacts();
  process.stdout.write("HFX-301 equivalence-eval — NL/direct-manipulation committed corpus check runner\n");
  const { scenarioSuite } = loadEquivalenceArtifacts();
  const pins = asRecord(scenarioSuite["pins"], "pins");
  process.stdout.write(
    `  suite: ${String(scenarioSuite["suiteId"])} v${String(scenarioSuite["version"])} (code ${String(scenarioSuite["codeVersion"])})\n`,
  );
  process.stdout.write(
    `  pins: taxonomy ${String(pins["taxonomyVersion"])} · compiler ${String(pins["compilerCodeVersion"])} · engine ${String(pins["engineKind"])}/${String(pins["engineCodeVersion"])}\n`,
  );
  process.stdout.write(`  corpus digest: ${String(pins["corpusDigest"])}\n`);
  for (const [cell, count] of Object.entries(report.summary.byExpectation)) {
    process.stdout.write(`  ${cell}: ${count} pairs\n`);
  }
  for (const outcome of loadEquivalenceArtifacts().outcomes) {
    const verdict =
      outcome.observed === "equivalent"
        ? `equivalent (${outcome.equalPoints ?? 0}/${COMPARISON_POINT_KINDS.length} points equal)`
        : outcome.observed === "declared-different"
          ? `declared-different [${outcome.differenceKinds?.join(", ")}] on [${outcome.divergentPoints?.join(", ")}]`
          : outcome.observed === "agent-refused"
            ? `agent-refused (${outcome.refusalReasonCode})`
            : `agent-clarification (${outcome.clarificationSlots?.join(", ")})`;
    process.stdout.write(
      `  [${outcome.expectationMet ? "met" : "MISMATCH"}] ${outcome.pairId}: ${verdict}\n`,
    );
  }
  process.stdout.write(`  provenance-manifest digest: ${report.summary.provenanceManifestDigest}\n`);
  process.stdout.write(`  benchmark-record digest: ${report.summary.benchmarkRecordDigest}\n`);
  process.stdout.write(
    `  provenance-only control: ${report.summary.provenanceOnlyControlVerdict} (the structural doctrine at journey level)\n`,
  );
  for (const entry of report.checks) {
    process.stdout.write(`  [${entry.passed ? "pass" : "FAIL"}] ${entry.id}: ${entry.detail}\n`);
  }
  process.stdout.write(report.ok ? "RUNNER: PASS\n" : "RUNNER: FAIL\n");
  process.exit(report.ok ? 0 : 1);
}
