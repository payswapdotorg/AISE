/**
 * HFX-301 — the natural-language / direct-manipulation EQUIVALENCE
 * benchmark CHECK RUNNER (the tools/ pickup — the building-benchmark
 * convention, mirroring tools/bim-eval/runner.ts).
 *
 * Wired into the root `bun run verify` (this directory's
 * benchmark.test.ts is a tools/ test, picked up by the root `bun test`).
 *
 * The boundary matrix forbids tools → packages/backend imports, so this
 * runner consumes the COMMITTED ARTIFACTS AS DATA — exactly the
 * bim-eval/solution-eval discipline: the committed corpus descriptor
 * (`tools/equivalence-eval/scenario.json`) and the committed golden run
 * (`fixtures/expected-outcomes.json`, regenerated by the backend-side
 * testkit where the harness, the compiler and the engine CAN be imported
 * — run `bun tools/equivalence-eval/runner.ts --update-goldens`). The
 * LIVE byte-for-byte regeneration check lives in the backend-side golden
 * test for the same boundary reason.
 *
 * What this runner proves over the committed data:
 *
 *  1. COHERENCE — both artifacts parse, their suite/benchmark identities
 *     agree and are pinned, the pair ids are unique and align 1:1 with
 *     the outcome ids, both files are canonical JSON, and the
 *     version-pinned manifest header (taxonomy version, engine
 *     kind+codeVersion, compiler codeVersion, corpus digest) rides BOTH
 *     headers identically;
 *  2. THE FOUR-CELL BEHAVIOR MATRIX — every expectation class is present
 *     (equivalent / declared-different / agent-refused /
 *     agent-clarification) and every outcome's observed cell satisfies
 *     its pair's declared expectation (the benchmark's own gate);
 *  3. THE EQUIVALENCE PROOF — every equivalent pair carries ZERO divergent
 *     comparison points over the four canonical journey points
 *     (operation identity, state digest, validation verdict, BOQ delta);
 *  4. THE HONEST DIFFERENCES — every declared-different pair carries ≥1
 *     divergent point, records the difference kind from the CLOSED
 *     vocabulary and its kind is exactly the declared one — never hidden;
 *  5. THE DESIGNED AGENT OUTCOMES — every agent-refused pair exhibits a
 *     refusal reason code from PROD-023's seven-code taxonomy (all seven
 *     present) with NO agent journey; every agent-clarification pair
 *     exhibits targeted questions over the five clarification slot kinds
 *     (all five present) — while the DIRECT journey applied everywhere;
 *  6. THE CONTROL-PLANE EMISSION — every outcome carries 64-hex
 *     content-addressed record + manifest ids, the aggregate digests are
 *     64-hex, and the provenance-only control verdict is 'equivalent'
 *     (the structural doctrine asserted at the journey level);
 *  7. THE INDEPENDENT SUMMARY RECOMPUTATION — the committed suite summary
 *     re-derives from the outcome rows alone (independent arithmetic),
 *     including the ordered-manifest-id digest (sha-256 over the
 *     canonical JSON of the ordered manifest ids).
 *
 * Determinism: pure reads of committed files + pure arithmetic; no clock,
 * no randomness, no network, no package imports.
 *
 * Exit code 0 = every check passed; 1 = a check failed (the gate).
 */

